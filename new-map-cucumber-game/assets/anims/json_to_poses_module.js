// json_to_poses_module.js -- turns an r15animlib export (<Name>.json: 15 fps pose samples,
// per bone quaternion w,x,y,z + optional translation in the Roblox joint frame) into a Luau
// ModuleScript the client can scrub without an Animation asset (Motor6D.Transform sampler).
//   node json_to_poses_module.js CucumberLift.json ../../CucumberLiftPoses.lua
// Output shape:
//   return { Name, Length, Fps, Joints = {"LowerTorso", ...},
//            Frames = { {t, {qw,qx,qy,qz,px,py,pz} per joint (flat, 7 numbers each)}, ... } }
const fs = require("fs");
const [,, inPath, outPath] = process.argv;
const data = JSON.parse(fs.readFileSync(inPath, "utf8"));
const JOINTS = ["LowerTorso", "UpperTorso", "Head", "LeftUpperArm", "LeftLowerArm", "LeftHand",
  "RightUpperArm", "RightLowerArm", "RightHand", "LeftUpperLeg", "LeftLowerLeg", "LeftFoot",
  "RightUpperLeg", "RightLowerLeg", "RightFoot"]; // HumanoidRootPart has no Motor6D
const f = (n) => {
  const s = Number(n).toFixed(4).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};
const lines = [];
lines.push("--[[");
lines.push(`\t${data.name}Poses  (ModuleScript, ReplicatedStorage.Modules) -- GENERATED by assets/anims/json_to_poses_module.js`);
lines.push(`\tfrom assets/anims/${data.name}.json (Blender, r15animlib.export_json). Pose samples the client scrubs by`);
lines.push("\tlift progress and writes straight into the R15 Motor6D.Transform values (no Animation asset,");
lines.push("\tso it plays on live servers whoever owns the place). Per frame: t, then 7 numbers per joint");
lines.push("\tin Joints order: qw, qx, qy, qz (rotation), px, py, pz (translation, studs, Roblox joint frame).");
lines.push("]]");
lines.push("return {");
lines.push(`\tName = "${data.name}",`);
lines.push(`\tLength = ${f(data.length)},`);
lines.push(`\tFps = ${data.fps},`);
lines.push(`\tJoints = {${JOINTS.map((j) => `"${j}"`).join(", ")}},`);
lines.push("\tFrames = {");
for (const fr of data.frames) {
  const nums = [];
  for (const j of JOINTS) {
    const e = fr.poses[j] || { q: [1, 0, 0, 0] };
    const q = e.q, p = e.p || [0, 0, 0];
    nums.push(f(q[0]), f(q[1]), f(q[2]), f(q[3]), f(p[0]), f(p[1]), f(p[2]));
  }
  lines.push(`\t\t{${f(fr.t)}, ${nums.join(", ")}},`);
}
lines.push("\t},");
lines.push("}");
fs.writeFileSync(outPath, lines.join("\r\n") + "\r\n");
console.log(`wrote ${outPath}: ${data.frames.length} frames, length ${data.length}, ${JOINTS.length} joints`);
