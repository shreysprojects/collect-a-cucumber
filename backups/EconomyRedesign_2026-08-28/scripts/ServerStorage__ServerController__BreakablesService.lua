--.. every zone's real spawn pool, in one place: its exclusive list if it has one
--.. (Spawn's mesh cucumbers), otherwise the historical shared TYPES plus that
--.. biome's ZONE_TYPES extras. Declared here, below ZONE_TYPES, so the upvalue
--.. actually resolves.
local function EffectiveTypes(zoneName)
	local exclusive = ZONE_EXCLUSIVE_TYPES[zoneName]
	if exclusive then return exclusive end
	local pool = {}
	for _, t in ipairs(TYPES) do pool[#pool + 1] = t end
	local biomeTypes = ZONE_TYPES[zoneName]
	if biomeTypes then
		for _, t in ipairs(biomeTypes) do pool[#pool + 1] = t end
	end
	return pool
end

--.. the sliced type this zone spawns for its dedicated sliced quota
local function SlicedTypeFor(zoneName)
	for _, t in ipairs(EffectiveTypes(zoneName)) do
		if t.Sliced then return t end
	end
	return nil
end

local function PickType(zoneName)
	--.. this zone can pick from the shared cucumbers PLUS its own biome cucumber
	local pool = {}
	-- Sliced cucumbers have a dedicated fixed quota and never consume a regular slot.
	for _,t in ipairs(EffectiveTypes(zoneName)) do
		if not t.Sliced then pool[#pool + 1] = t end
	end
	--.. GOLDEN HOUR no longer boosts a golden TYPE's weight (there is no golden type
	--.. any more) -- it multiplies the per-spawn golden CHANCE in GoldenChanceFor,
	--.. so the frenzy turns every kind of cucumber gold, not just one shape.
	local function weightOf(t)
		return t.Weight
	end
	local total = 0
	for _,t in ipairs(pool) do total += weightOf(t) end
	local roll = math.random(1, total)
	local counter = 0
	for _,t in ipairs(pool) do
		counter += weightOf(t)
		if roll <= counter then return t end
	end
	return pool[1]
end

