	local leaf = Instance.new("Part")
	leaf.Name = "Leaf"
	leaf.Shape = Enum.PartType.Ball
	leaf.Size = Vector3.new(part.Size.Y * 0.42, part.Size.Y * 0.2, part.Size.Y * 0.55)
	leaf.Color = Color3.fromRGB(38, 96, 32)
	leaf.Material = Enum.Material.Grass
	leaf.Anchored = false
	leaf.CanCollide = false
	leaf.CanQuery = false
	leaf.CFrame = part.CFrame * CFrame.new(0, part.Size.Y * 0.45, -part.Size.Z * 0.4) * CFrame.Angles(math.rad(-25), 0, 0)
	leaf.Parent = part
	local weld = Instance.new("WeldConstraint")
	weld.Part0 = part
	weld.Part1 = leaf
	weld.Parent = leaf
end

