		-- Workspace, so carry flesh and seeds by the same root delta explicitly.
		local delta = newRootCFrame * oldRootCFrame:Inverse()
		for _, child in ipairs(part:GetChildren()) do
			if child:IsA("BasePart") and child.Name ~= "Shadow" then
				child.CFrame = delta * child.CFrame
			end
