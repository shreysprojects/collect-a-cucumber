				local ok, err = pcall(function()
					ServerController.GetModule(def.EffectModule).SetZoneEventActive(zoneName, enabled)
				end)
				if not ok then
					warn("[BreakablesService] event effect failed for", eventId, err)
				end
			end
		end
	end
end

local function SyncEventAttributes(zoneName)
	local meter = BossProgress[zoneName]
	if not meter then return end
	local state = GetEventState(zoneName)
	meter:SetAttribute("EventPhase", state.Phase)
	meter:SetAttribute("EventName", state.ActiveEvent and state.ActiveEvent.Name or "")
	meter:SetAttribute("EventId", state.ActiveEvent and state.ActiveEvent.Id or "")
	meter:SetAttribute("EventProgress", state.Progress)
	meter:SetAttribute("EventRequired", state.Required)
end

local function BeginEvent(zoneName)
	local state = GetEventState(zoneName)
	local meter = BossProgress[zoneName]
	if state.Phase ~= "Goal" or not state.ActiveEvent or not meter then return end
	state.Phase = "Active"
	state.Token += 1
	local token = state.Token
	local duration = state.ActiveEvent.Duration or EVENT_DURATION
	SyncEventAttributes(zoneName)
	meter:SetAttribute("EventDuration", duration)
	meter:SetAttribute("EventEndsAt", workspace:GetServerTimeNow() + duration)
	SetEventEffect(zoneName, state.ActiveEvent.Id, true)
	-- The biome travel popup observes the replicated Active phase; no start toast.
	task.delay(duration, function()
		if state.Token ~= token or state.Phase ~= "Active" or not state.ActiveEvent then return end
		local endedEvent = state.ActiveEvent
		state.Phase = "None"
		state.ActiveEvent = nil
		state.Progress = 0
		SetEventEffect(zoneName, endedEvent.Id, false)
		meter.Value = 0 -- restart the cucumber-break path toward the next boss
		meter:SetAttribute("EventEndsAt", 0)
		SyncEventAttributes(zoneName)
		Network:FireAllClients("Notif", {
			Message = ("%s IS OVER IN %s!"):format(endedEvent.Name, string.upper(zoneName));
			Type = "Error";
		})
	end)
end

local function PlayersInBiome(zoneName)
	local count = 0
	for _, Player in ipairs(Players:GetPlayers()) do
		local current = FindPlayerBiome(Player) or PlayerEventZone[Player]
		if current == zoneName then count += 1 end
	end
	return math.max(1, count)
end

StartEventChallenge = function(zoneName)
	local state = GetEventState(zoneName)
	local meter = BossProgress[zoneName]
	if state.Phase ~= "None" or not meter then return end
	--.. selector eligibility: events with MinPlayersInBiome only enter the
	--.. rotation when that many players are here at SELECTION time (raw
	--.. headcount, not the max(1,..) the goal scaler uses). Admin starts bypass.
	local playerCount = 0
	for _, Player in ipairs(Players:GetPlayers()) do
		local current = FindPlayerBiome(Player) or PlayerEventZone[Player]
		if current == zoneName then playerCount += 1 end
	end
	local choices = {}
	for _, definition in ipairs(EVENT_DEFS) do
		if definition.Id ~= state.LastEventId and playerCount >= (definition.MinPlayersInBiome or 0) then
			table.insert(choices, definition)
		end
	end
	if #choices == 0 then
		--.. the only eligible event was also the last one played: allow the repeat
		for _, definition in ipairs(EVENT_DEFS) do
			if playerCount >= (definition.MinPlayersInBiome or 0) then
				table.insert(choices, definition)
			end
		end
	end
	if #choices == 0 then return end
	state.ActiveEvent = choices[math.random(1, #choices)]
	state.LastEventId = state.ActiveEvent.Id
	state.Phase = "Goal"
	state.Progress = 0
	state.Required = EVENT_GOAL_BASE + EVENT_GOAL_PER_EXTRA_PLAYER * (PlayersInBiome(zoneName) - 1)
	meter.Value = 0
	meter:SetAttribute("EventEndsAt", 0)
	SyncEventAttributes(zoneName)
end

RecordEventHit = function(zoneName)
	local state = GetEventState(zoneName)
	if state.Phase ~= "Goal" then return end
	state.Progress = math.min(state.Progress + 1, state.Required)
	local meter = BossProgress[zoneName]
	if meter then meter:SetAttribute("EventProgress", state.Progress) end
	if state.Progress >= state.Required then BeginEvent(zoneName) end
end

--.. The client asks permission before opening Roblox's purchase prompt. The
--.. server pins the request to the player's current biome so exploiters cannot
--.. buy against another biome or request a skip while a boss/event is live.
function BreakablesService.RequestRequirementSkip(Player, zoneName)
	if typeof(zoneName) ~= "string" or not Player or Player.Parent ~= Players then return false end
	local currentZone = FindPlayerBiome(Player) or PlayerEventZone[Player]
	if currentZone ~= zoneName then return false end
	local meter = BossProgress[zoneName]
	if not meter or meter:GetAttribute("BossActive") == true then return false end
	local phase = GetEventState(zoneName).Phase
	if phase ~= "None" and phase ~= "Goal" then return false end
	Player:SetAttribute("PendingRequirementSkipZone", zoneName)
	return true
end

--.. Called only by ProductHandler's authoritative ProcessReceipt. If another
--.. player finishes the requirement while the purchase window is open, the
--.. receipt remains pending and Roblox retries it once this biome is eligible.
function BreakablesService.GrantRequirementSkip(Player)
	if not Player or Player.Parent ~= Players then return false end
	local zoneName = Player:GetAttribute("PendingRequirementSkipZone") or Player:GetAttribute("CurrentBiome")
	local meter = typeof(zoneName) == "string" and BossProgress[zoneName] or nil
	if not meter or meter:GetAttribute("BossActive") == true then return false end

	local state = GetEventState(zoneName)
	if state.Phase == "Goal" and state.ActiveEvent then
		state.Progress = state.Required
		SyncEventAttributes(zoneName)
		BeginEvent(zoneName)
		Player:SetAttribute("PendingRequirementSkipZone", nil)
		return true
	elseif state.Phase == "None" then
		meter.Value = 0
		meter:SetAttribute("BossActive", true) -- close the race before the deferred spawn
		Player:SetAttribute("PendingRequirementSkipZone", nil)
		task.defer(BreakablesService.SpawnBoss, zoneName)
		return true
	end
	return false
end

--.. Admin API is biome-scoped. Starting skips that biome's hit challenge.
function BreakablesService.StartEvent(eventId, zoneName)
	local meter = BossProgress[zoneName]
	if not meter then return false, "PICK A VALID BIOME" end
	local definition
	for _, candidate in ipairs(EVENT_DEFS) do
		if candidate.Id == eventId then definition = candidate break end
	end
	if not definition then return false, "UNKNOWN EVENT" end

	local state = GetEventState(zoneName)
	local previousEvent = state.Phase == "Active" and state.ActiveEvent or nil
	state.Token += 1
	state.ActiveEvent = definition
	state.LastEventId = definition.Id
	state.Phase = "Active"
	state.Progress = state.Required
	meter.Value = 0
	local duration = definition.Duration or EVENT_DURATION
	SyncEventAttributes(zoneName)
	meter:SetAttribute("EventDuration", duration)
	meter:SetAttribute("EventEndsAt", workspace:GetServerTimeNow() + duration)
	if previousEvent then SetEventEffect(zoneName, previousEvent.Id, false) end
	SetEventEffect(zoneName, definition.Id, true)
	-- Admin starts use the same replicated Active phase and popup, without a toast.
	--.. Admin-started events use the registry duration (2-minute default) and
	--.. return this biome to its normal cucumber-break meter, never latched on.
	local token = state.Token
	task.delay(duration, function()
		if state.Token ~= token or state.Phase ~= "Active" or state.ActiveEvent ~= definition then return end
		state.Phase = "None"
		state.ActiveEvent = nil
		state.Progress = 0
		SetEventEffect(zoneName, definition.Id, false)
		meter.Value = 0
		meter:SetAttribute("EventEndsAt", 0)
		SyncEventAttributes(zoneName)
		Network:FireAllClients("Notif", {
			Message = ("%s IS OVER IN %s!"):format(definition.Name, string.upper(zoneName));
			Type = "Error";
		})
	end)
	return true, definition.Name
end

function BreakablesService.StopEvent(zoneName)
	local meter = BossProgress[zoneName]
	if not meter then return false, "PICK A VALID BIOME" end
	local state = GetEventState(zoneName)
	local hadEvent = state.Phase ~= "None"
	local endedEvent = state.ActiveEvent
	local endedName = endedEvent and endedEvent.Name
	state.Token += 1
	state.Phase = "None"
	state.ActiveEvent = nil
	state.Progress = 0
	if endedEvent then SetEventEffect(zoneName, endedEvent.Id, false) end
	meter.Value = 0 -- admin stop also restarts the cucumber-break path
	meter:SetAttribute("EventEndsAt", 0)
	SyncEventAttributes(zoneName)
	if hadEvent then
		Network:FireAllClients("Notif", {
			Message = ("%s STOPPED IN %s."):format(endedName or "THE EVENT", string.upper(zoneName));
			Type = "Error";
		})
	end
	return hadEvent, endedName
end
function BreakablesService.Initialize()
	--.. same handler as the ClickDetector; lets taps route through a remote too
	Network:BindEvents({
		SmashBreakable = function(Player, part)
			if typeof(part) ~= "Instance" or not part:IsA("BasePart") then return end
			if not Breakables[part] and part.Parent and part.Parent:IsA("BasePart") and Breakables[part.Parent] then
				part = part.Parent -- clicked the slice's flesh core
			end
			OnClicked(Player, part)
		end,

		PickaxeStrike = function(Player, part, indirect)
			if typeof(part) ~= "Instance" or not part:IsA("BasePart") then return end
			if not Breakables[part] and part.Parent and part.Parent:IsA("BasePart") and Breakables[part.Parent] then
				part = part.Parent -- clicked the slice's flesh core
			end
			BreakablesService.PickaxeStrike(Player, part, indirect == true)
		end,

		ToggleAutoFarm = function(Player)
			BreakablesService.ToggleAutoFarm(Player)
		end,
	})

	Container = workspace:FindFirstChild("Breakables")
	if not Container then
		Container = Instance.new("Folder")
		Container.Name = "Breakables"
		Container.Parent = workspace
	end
	local folders = {}
	for _,zone in ipairs(ZONES) do
		local f = Container:FindFirstChild(zone)
		if not f then
			f = Instance.new("Folder")
			f.Name = zone
			f.Parent = Container
		end
		folders[zone] = f
	end
	Container = folders

	Players.PlayerRemoving:Connect(function(Player)
		Targets[Player] = nil
		LastClick[Player] = nil
		NextAuto[Player] = nil
		PickaxeReady[Player] = nil
		Combo[Player] = nil
		ComboExpire[Player] = nil
		LastAutoFarmZone[Player] = nil
		for _,data in pairs(Breakables) do
			data.Damagers[Player] = nil
		end
	end)

	table.clear(Population)
	table.clear(SlicedPool)
	table.clear(OtherPool)

	-- One paced, round-robin worker owns all normal population changes. It never
	-- creates or removes a biome's entire deficit in one scheduler cycle, which
	-- prevents replication/streaming bursts when the nearest biome changes.
	task.spawn(function()
		local active = BreakablesService.ActiveZones()
		local nextPlan = os.clock() + POPULATION_PLAN_TICK
		local cursor = 1
		while true do
			local baselineReady = true
			for _, zoneName in ipairs(ZONES) do
				local sliced, other = BreakablesService.CountZonePopulation(zoneName)
				if sliced < EMPTY_ZONE_SLICED or other < EMPTY_ZONE_OTHER then
					baselineReady = false
					break
				end
			end
			task.wait(baselineReady and POPULATION_WORK_TICK or POPULATION_STARTUP_TICK)

			if os.clock() >= nextPlan then
				active = BreakablesService.ActiveZones()
				nextPlan = os.clock() + POPULATION_PLAN_TICK
			end

			for offset = 0, #ZONES - 1 do
				local index = ((cursor + offset - 1) % #ZONES) + 1
				local zone = ZONES[index]
				local folder = Container and Container[zone]
				if folder then
					local slicedTarget, otherTarget = BreakablesService.ZoneTargets(zone, active)
					local sliced, other = BreakablesService.CountZonePopulation(zone)
					local didWork = false

					if sliced < slicedTarget then
						BreakablesService.SpawnBreakable(zone, true)
						didWork = true
					elseif other < otherTarget then
						BreakablesService.SpawnBreakable(zone, false)
						didWork = true
					elseif sliced > slicedTarget or other > otherTarget then
						BreakablesService.PruneZone(zone, slicedTarget, otherTarget)
						didWork = true
					end

					if didWork then
						cursor = (index % #ZONES) + 1
						break
					end
				end
			end
		end
	end)

	--.. Golden Hour is now started by the post-boss event challenge above.

	--.. LIGHTNING STRIKES: every biome independently rolls a new 30-90 second
	--.. delay before every strike, including its first one.
	for _, zoneName in ipairs(ZONES) do
		task.spawn(function()
			while true do
				task.wait(math.random(LIGHTNING_MIN, LIGHTNING_MAX))
				BreakablesService.LightningStrike(zoneName)
			end
		end)
	end

	--.. DEV HOOK: paste  workspace:SetAttribute("LightningDev", "Spawn")  into the
	--.. SERVER dev console to strike that zone immediately (same pattern as SpawnBossDev).
	workspace:GetAttributeChangedSignal("LightningDev"):Connect(function()
		local zone = workspace:GetAttribute("LightningDev")
		if type(zone) ~= "string" or zone == "" then return end
		workspace:SetAttribute("LightningDev", nil)
		if not table.find(ZONES, zone) then
			warn(("[LightningDev] unknown zone '%s' — zones: %s"):format(tostring(zone), table.concat(ZONES, ", ")))
			return
		end
		print(("[LightningDev] striking a cucumber in %s"):format(zone))
		BreakablesService.LightningStrike(zone)
	end)

	--.. DEV HOOK: paste  workspace:SetAttribute("LightningBreakDev", "PlayerName")  into
	--.. the SERVER dev console to force-break a live charged cucumber crediting that
	--.. player — verifies the rolled 20x-1000x payout end to end through Break().
	workspace:GetAttributeChangedSignal("LightningBreakDev"):Connect(function()
		local name = workspace:GetAttribute("LightningBreakDev")
		if type(name) ~= "string" or name == "" then return end
		workspace:SetAttribute("LightningBreakDev", nil)
		local plr = Players:FindFirstChild(name)
		if not plr then
			warn("[LightningBreakDev] no player named " .. name)
			return
		end
		for part, data in pairs(Breakables) do
			if data.Lightning and part.Parent then
				local fullDamage = math.max(1, tonumber(data.MaxHP) or 1)
				data.HP = 0
				data.Hits = math.max(1, data.Hits or 0)
				data.LastAttacker = plr
				data.Damagers = {[plr] = fullDamage}
				data.PetDamagers = {}
				print(("[LightningBreakDev] breaking a %dX charged %s in %s for %s"):format(data.Lightning, data.Type.Name, data.Zone, name))
				Break(part, data)
				return
			end
		end
		warn("[LightningBreakDev] no charged cucumber alive — strike one first with LightningDev")
	end)

	--.. per-player state must not outlive the player
	Players.PlayerRemoving:Connect(function(Player)
		Targets[Player] = nil
		LastClick[Player] = nil
		NextAuto[Player] = nil
		PickaxeReady[Player] = nil
		Combo[Player] = nil
		ComboExpire[Player] = nil
		PendingSwitch[Player] = nil
	end)

	--.. THE COLOSSAL CUCUMBER: every zone has a break meter (replicated for the
	--.. client HUD bar); filling it summons that zone's boss. Kills pay by
	--.. contribution through the normal Break() split.
	do
		local meters = Instance.new("Folder")
		meters.Name = "BossProgress"
		meters:SetAttribute("Required", BOSS_BREAKS)
		for _,zone in ipairs(ZONES) do
			local v = Instance.new("IntValue")
			v.Name = zone
			v.Value = 0
			--.. per-zone summon cost + boss name, read by the client HUD bar
			local def = BOSS_TYPES[zone] or BOSS_TYPES.Spawn
			v:SetAttribute("Required", def.Breaks)
			v:SetAttribute("BossName", def.Name)
			v:SetAttribute("BossActive", false)
			v:SetAttribute("BossHP", 0)
			v:SetAttribute("BossMaxHP", 0)
			v.Parent = meters
			BossProgress[zone] = v
			GetEventState(zone)
			v:SetAttribute("EventEndsAt", 0)
			SyncEventAttributes(zone)
		end
		BossProgressFolder = meters
		meters.Parent = ReplicatedStorage

		local skipRequest = ReplicatedStorage:FindFirstChild("RequestBossEventSkip")
		if not skipRequest then
			skipRequest = Instance.new("RemoteFunction")
			skipRequest.Name = "RequestBossEventSkip"
			skipRequest.Parent = ReplicatedStorage
		end
		skipRequest.OnServerInvoke = function(Player, zoneName)
			return BreakablesService.RequestRequirementSkip(Player, zoneName)
		end

		for _, Player in ipairs(Players:GetPlayers()) do WatchEventPlayer(Player) end
		Players.PlayerAdded:Connect(WatchEventPlayer)
		Players.PlayerRemoving:Connect(function(Player)
			watchedEventPlayers[Player] = nil
			PlayerEventZone[Player] = nil
		end)
		StartEventPlayerLoop()

		--.. summon cost scales with the server population: +5% of the zone's base
		--.. Breaks for EVERY player in the server — each join adds 5%, each leave
		--.. removes it. Break()'s spawn check and the client HUD bar both read the
		--.. live "Required" attribute every time, so mid-session changes just work.
		local function refreshRequired()
			local mult = 1 + BOSS_REQ_PER_PLAYER * #Players:GetPlayers()
			for zone, v in pairs(BossProgress) do
				local def = BOSS_TYPES[zone] or BOSS_TYPES.Spawn
				v:SetAttribute("Required", math.floor(def.Breaks * mult + 0.5))
			end
		end
		Players.PlayerAdded:Connect(refreshRequired)
		Players.PlayerRemoving:Connect(function()
			task.defer(refreshRequired) -- recount after the leaver is actually gone
		end)
		refreshRequired()
	end

	--.. DEV HOOK: set StartEventDev to "Biome:EventId", for example
	--.. "Desert:GoldenHour". With no biome prefix it defaults to Spawn.
	workspace:GetAttributeChangedSignal("StartEventDev"):Connect(function()
		local request = workspace:GetAttribute("StartEventDev")
		if type(request) ~= "string" or request == "" then return end
		workspace:SetAttribute("StartEventDev", nil)
		local zoneName, eventId = request:match("^([^:]+):(.+)$")
		if not zoneName then zoneName, eventId = "Spawn", request end
		local started, result = BreakablesService.StartEvent(eventId, zoneName)
		print(("[StartEventDev] %s in %s: %s"):format(tostring(eventId), tostring(zoneName), started and "started" or tostring(result)))
	end)

	--.. DEV HOOK: paste  workspace:SetAttribute("SpawnBossDev", "Spawn")  into the
	--.. SERVER dev console (or Studio command bar during a playtest) to force-summon
	--.. that zone's boss. Attribute-based so it works from any console context — a
	--.. console require() of this module gets a separate, stateless copy and no-ops.
	--.. Safe: client attribute writes never replicate, so players can't trigger it.
	workspace:GetAttributeChangedSignal("SpawnBossDev"):Connect(function()
		local zone = workspace:GetAttribute("SpawnBossDev")
		if type(zone) ~= "string" or zone == "" then return end
		workspace:SetAttribute("SpawnBossDev", nil)
		if not BOSS_TYPES[zone] then
			warn(("[SpawnBossDev] unknown zone '%s' — zones: Spawn, Desert, Samurai, Farm, Snow, Underwater, Volcano, Narmek"):format(tostring(zone)))
			return
		end
		print(("[SpawnBossDev] summoning the %s boss (if nothing appears, that zone's boss is already up)"):format(zone))
		BreakablesService.SpawnBoss(zone)
	end)

	--.. DEV HOOK: paste  workspace:SetAttribute("KillBossDev", "Spawn:PlayerName")  into
	--.. the SERVER dev console to force-kill that zone's live boss through the normal
	--.. Break() path, crediting that player with all the damage (omit ":PlayerName" to
	--.. credit the first player). Exercises the boss-trophy award + chat announcement.
	workspace:GetAttributeChangedSignal("KillBossDev"):Connect(function()
		local value = workspace:GetAttribute("KillBossDev")
		if type(value) ~= "string" or value == "" then return end
		workspace:SetAttribute("KillBossDev", nil)
		local zone, name = string.match(value, "^([^:]+):?(.*)$")
		local plr = (name ~= "" and Players:FindFirstChild(name)) or Players:GetPlayers()[1]
		local ok = BreakablesService.KillBoss(zone, plr)
		print(("[KillBossDev] %s boss: %s"):format(tostring(zone), ok and ("killed, credited " .. tostring(plr and plr.Name)) or "no boss up"))
	end)

	--.. DEV HOOK: paste  workspace:SetAttribute("PrintPlaytimeDev", true)  into the
	--.. SERVER dev console to print every online player's lifetime playtime.
	--.. Source of truth = profile TotalStats.TotalTime, which CurrencyHandler's
	--.. Initialize loop ticks +1 every second the player is online (all sessions).
	workspace:GetAttributeChangedSignal("PrintPlaytimeDev"):Connect(function()
		if not workspace:GetAttribute("PrintPlaytimeDev") then return end
		workspace:SetAttribute("PrintPlaytimeDev", nil)
		print("---- TOTAL PLAYTIME (lifetime, all sessions) ----")
		for _, plr in ipairs(Players:GetPlayers()) do
			local userData = ProfileService.GetUserData(plr)
			local seconds = userData and userData.TotalStats and tonumber(userData.TotalStats.TotalTime)
			if seconds then
				seconds = math.floor(seconds)
				print(("%s (@%s): %dh %02dm %02ds  (%d seconds)"):format(
					plr.DisplayName, plr.Name,
					math.floor(seconds / 3600), math.floor(seconds % 3600 / 60), seconds % 60, seconds))
			else
				print(("%s (@%s): profile not loaded"):format(plr.DisplayName, plr.Name))
			end
		end
	end)

	--.. one click = full commitment for normal farming. Owned + enabled Autofarm
	--.. continuously acquires targets from the current/last biome with no distance leash.
	while true do
		task.wait(0.25)
		local now = os.clock()

		for _, plr in ipairs(Players:GetPlayers()) do
			if IsAutoFarmEnabled(plr) then
				local zone = RefreshAutoFarmZone(plr)
				local target = Targets[plr]
				local targetData = target and Breakables[target]
				if zone and targetData and targetData.Zone ~= zone then
					Targets[plr] = nil
				end
				if zone and not Targets[plr] then
					RetargetNearest(plr)
				end
			end

			-- Mirror the authoritative target so each client visibly moves its pets.
			local pd = plr:FindFirstChild("PlayerData")
			local ov = pd and pd:FindFirstChild("AutoTarget")
			if ov and ov.Value ~= Targets[plr] then
				ov.Value = Targets[plr]
			end
		end

		for plr, part in pairs(Targets) do
			local char = plr.Character
			local hrp = char and char:FindFirstChild("HumanoidRootPart")
			local autoFarm = IsAutoFarmEnabled(plr)
			if not Breakables[part] then
				Targets[plr] = nil
			elseif not hrp or (not autoFarm and (hrp.Position - part.Position).Magnitude > AUTO_LEASH) then
				Targets[plr] = nil
			elseif now >= (NextAuto[plr] or 0) then
				--.. The beat only advances on a hit that actually lands. While the swarm is
				--.. still travelling the timer stays ready, so the first hit fires the moment
				--.. they arrive (<=0.25s) instead of waiting out a full AUTO_TICK.
				if EquippedPets(plr) > 0 and PetsInRange(plr, part) then
					NextAuto[plr] = now + AUTO_TICK
					ApplyDamage(plr, part, DamageOf(plr))
				end
			end
		end
	end
end

return BreakablesService
