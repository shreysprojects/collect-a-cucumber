local function SetEventEffect(zoneName, eventId, enabled)
	if eventId == "GoldenHour" then
		if enabled then ChurnGoldenCucumbers(zoneName) end
	elseif eventId == "SuperStrength" then
		SetSuperStrength(zoneName, enabled)
	else
		--.. registry events with an external effect module (CucumberSmash ->
		--.. SmashEventService per-zone scores/rewards). pcall: a broken event
		--.. module must never wedge the zone's event state machine.
		for _, def in ipairs(EVENT_DEFS) do
