		wasPooled = part ~= nil
		if not part then
			part = BuildCucumber(template.Color, typeDef.Scale * 0.75, typeDef.Golden == true, typeDef.Color, typeDef.Material, typeDef.Glow)
		end
		part.Name = typeDef.Name
	end

	part.Name = typeDef.Name
	if wasPooled then
		-- Defensive reset: a reusable object must never carry an old mutation's
		-- descriptor, light, sparkles, color, material, or label into its next life.
		BreakablesService.ClearMutationVisual(part)
		if typeDef.Sliced then
			part.Color = Color3.fromRGB(72, 132, 60)
			part.Material = Enum.Material.SmoothPlastic
