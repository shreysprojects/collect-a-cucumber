--.. Rebuild a DROPPED carried cucumber (CarryService) as a real breakable at
--.. `position` (a ground point): full HP + bar, standard 0.75 world scale, and
--.. the golden look preserved via the stored typeDef. Template types only --
--.. CarryService only awards carries for those. Mutation/lightning charge do
--.. not survive the trip. Declared down here so every upvalue it borrows from
--.. SpawnBreakable already exists (locals must precede the closures that use
--.. them); adds NO top-level locals -- this module is AT the 200-local limit.
function BreakablesService.SpawnCarriedAt(zoneName, typeDef, position)
	if type(typeDef) ~= "table" or not typeDef.Template then return false end
	if not Container or not Container[zoneName] then return false end
	local Templates = Assets:FindFirstChild("BreakableModels")
	local modelTemplate = Templates and Templates:FindFirstChild(typeDef.Template)
	if not modelTemplate then return false end

	local maxHP = math.floor(typeDef.HP * (ZONE_HP[zoneName] or 1))
	local model = modelTemplate:Clone()
	model.Name = typeDef.Name
	model:ScaleTo(model:GetScale() * 0.75)
	model:SetAttribute("EventVisualScale", 1)
	local ext = model:GetExtentsSize()
	model:PivotTo(CFrame.new(position + Vector3.new(0, ext.Y / 2, 0)) * CFrame.Angles(0, math.rad(math.random(-180, 180)), 0))

	local part = model.PrimaryPart
	if not part then
		model:Destroy()
		return false
	end
	local visual = model:FindFirstChild("Canopy") or model:FindFirstChild("Trunk")

	local bar, hpLabel = BuildBillboard(part, typeDef, maxHP)
	local click = Instance.new("ClickDetector")
	click.MaxActivationDistance = 70
	click.Parent = part
	click.MouseClick:Connect(function(Player)
		OnClicked(Player, part)
	end)

	local entry = {
		Type = typeDef;
		HP = maxHP;
		MaxHP = maxHP;
		Zone = zoneName;
		Bar = bar;
		HPLabel = hpLabel;
		Damagers = {};
		Hits = 0;
		Holder = model;
		ChunkColor = visual and visual.Color or nil;
		Carried = true; -- player-dropped: exempt from PruneZone's over-target culling
	}
	if typeDef.Golden then
		ApplyGoldenLook(model)
		entry.ChunkColor = GOLDEN_COLOR
	elseif typeDef.Diamond then
		MUTATIONS.DiamondMod.ApplyLook(model)
		entry.ChunkColor = MUTATIONS.DiamondMod.Color
	end

	Breakables[part] = entry
	BreakablesService.TrackAdded(entry)
	model.Parent = Container[zoneName]
	return true
end

--.. Effective spawn probability of this exact breakable -- LOWER = RARER.
--.. CarryService compares these to decide whether a fresh break out-rares the
--.. cucumber already on the player's arm. Accounts for: the type's Weight
--.. share of its own biome pool, biome tier (each later ZONES entry halves
--.. the odds), the golden roll, the mutation roll, and lightning charges.
--.. Declared next to SpawnCarriedAt for the same upvalue-ordering reason;
--.. adds NO top-level locals (module is AT the 200-local limit).
function BreakablesService.CarryRarityOf(data)
	local typeDef = data.Type
	local total = 0
	for _, t in ipairs(EffectiveTypes(data.Zone)) do
		total += (t.Weight or 10)
	end
	local p = (typeDef.Weight or 10) / math.max(total, 1)

	local tier = table.find(ZONES, data.Zone) or 1
	p /= 2 ^ (tier - 1)

	if typeDef.Golden then
		p *= math.clamp(GoldenChanceFor(data.Zone), 0.001, 1)
	end
	if data.Mutation then
		p *= MUTATION_CHANCE
	end
	if data.Lightning then
		p *= 0.05
	end
	if data.Type.Diamond then
		p *= MUTATIONS.DiamondMod.Chance
	end
	return p
end

--.. Resolve a zone's live type def by display name -- vault persistence
--.. (VaultService) rebuilds saved cucumbers through this. Declared next to
--.. CarryRarityOf for the same EffectiveTypes upvalue-ordering reason;
--.. adds NO top-level locals (module is AT the 200-local limit).
--.. admin panel (2026-08-27): spawn ONE cucumber with a chosen mutation.
--.. mutationName = a rotation name, "PRISMATIC", or "TODAY"/nil. Rides
--.. MUTATIONS.ForceNext (the chunk is at the 200-local cap), consumed by the
--.. spawn roll sites before any random rolls; the SpawnBreakable call below is
--.. synchronous, so the flag can't leak into an organic spawn.
function BreakablesService.SpawnMutatedDev(zoneName, mutationName)
	if mutationName == "DIAMOND" then
		--.. DIAMOND is the material modifier: force it at the type-pick instead
		MUTATIONS.ForceDiamond = zoneName
		BreakablesService.SpawnBreakable(zoneName, false)
		local landed = MUTATIONS.ForceDiamond == nil
		MUTATIONS.ForceDiamond = nil
		return landed, "DIAMOND"
	end
	local mut
	if mutationName == "PRISMATIC" then
		mut = MUTATIONS.Prismatic
	elseif mutationName == "TODAY" or mutationName == nil then
		mut = TodaysMutation()
	else
		for _, m in ipairs(MUTATIONS) do
			if m.Name == mutationName then mut = m break end
		end
	end
	if not mut then return false end
	MUTATIONS.ForceNext = {Zone = zoneName; Mut = mut;}
	BreakablesService.SpawnBreakable(zoneName, false)
	local landed = MUTATIONS.ForceNext == nil
	MUTATIONS.ForceNext = nil
	return landed, mut.Name
end

--.. quest board (2026-08-27): enumerate a zone's spawnable produce for the
--.. random catch-target roll (name + weight only; the defs stay private)
function BreakablesService.TypeNamesFor(zoneName)
	local list = {}
	for _, t in ipairs(EffectiveTypes(zoneName)) do
		list[#list + 1] = {Name = t.Name; Weight = t.Weight or 1}
	end
	return list
end

function BreakablesService.FindType(zoneName, typeName)
	for _, t in ipairs(EffectiveTypes(zoneName)) do
		if t.Name == typeName then return t end
	end
	--.. BOSS TROPHY (2026-08-27): vault persistence resolves a stored boss
	--.. cucumber back to its BOSS_TYPES def (Boss=true routes CarryService's
	--.. BuildFromTemplate to BuildBossVisual instead of a template model)
	local bossDef = BOSS_TYPES[zoneName]
	if bossDef and bossDef.Name == typeName then return bossDef end
	return nil
end

--.. Parentless boss REPLICA (a Model) for carry/vault trophy visuals
--.. (2026-08-27); accepts a BOSS_TYPES def (what FindType returns for boss
--.. names). The caller owns (and must destroy) the returned model. Mirrors
--.. BuildMobileBossRig's LIVE look exactly (user call, same day — NOT the
--.. parked AddBossCharacter visuals): head decorations shaved, body stood
--.. upright, AddUprightLimbsAndFace limbs/fists/feet, no face plate. The
--.. PrimaryPart is an invisible UPRIGHT root: DisplayOn (vault podiums) and
--.. GiveCarry re-pose models by the primary's frame with yaw-only rotation,
--.. and the body cylinder's own frame lies on its side — an upright root is
--.. what keeps the character STANDING on podiums.
function BreakablesService.BuildBossVisual(def)
	if type(def) ~= "table" or def.Boss ~= true then return nil end
	local part = BuildCucumber(def.Color, def.Scale, false, def.Color, def.Material, def.Glow)
	for _, c in ipairs(part:GetChildren()) do
		if c.Name == "Stem" or c.Name == "Vine" or c.Name == "Leaf" then
			c:Destroy() -- same head-shave as the walking rig
		end
	end
	local len = part.Size.X
	local dia = part.Size.Y
	local legLen = dia * 0.55
	local hrpCF = CFrame.new(0, len * 0.5 + legLen * 0.55 + 0.1, 0)
	part.CFrame = hrpCF * CFrame.Angles(0, 0, math.rad(90))
	for _, c in ipairs(part:GetChildren()) do
		if c:IsA("BasePart") then c.CFrame = part.CFrame * c.CFrame end
	end
	pcall(AddUprightLimbsAndFace, part, def, hrpCF, dia, len)

	local model = Instance.new("Model")
	model.Name = def.Name
	local root = Instance.new("Part")
	root.Name = "TrophyRoot"
	root.Size = Vector3.new(dia * 0.5, len * 0.5, dia * 0.5)
	root.Transparency = 1
	root.CFrame = hrpCF
	root.Parent = model
	part.Parent = model
	model.PrimaryPart = root
	return model
end

function BreakablesService.SpawnBoss(zone)
	zone = zone or "Spawn"
	local def = BOSS_TYPES[zone] or BOSS_TYPES.Spawn
	local folder = Container and Container[zone]
	if not folder or folder:FindFirstChild(def.Name) then return end -- one per zone

	local maxHP = math.floor((def.HPBase + BOSS_HP_PER_PLAYER * math.max(0, #Players:GetPlayers() - 1)) * (ZONE_HP[zone] or 1))

	local part = BuildCucumber(def.Color, def.Scale, false, def.Color, def.Material, def.Glow)
	part.Name = def.Name
	part:SetAttribute("BossHP", maxHP)
	part:SetAttribute("BossMaxHP", maxHP)
	local meter = BossProgress[zone]
	if meter then
		meter.Value = 0
		meter:SetAttribute("BossActive", true)
		meter:SetAttribute("BossHP", maxHP)
		meter:SetAttribute("BossMaxHP", maxHP)
	end

	local point = GetZonePoint(zone)
	local bossModel
	if def.Mobile then
		--.. MOBILE BOSS: upright walking character (no anchored blob shadow — the
		--.. anchored shadow part would stay behind while the boss walks away)
		bossModel = BuildMobileBossRig(part, def, point)
	else
		--.. bosses rest on the ground too: same tipped-cylinder contact math as regular spawns
		local bossTilt = math.rad(6)
		local bossLift = part.Size.Y * 0.5 * math.cos(bossTilt) + part.Size.X * 0.5 * math.sin(bossTilt) + 0.05
		part.CFrame = CFrame.new(point + Vector3.new(0, bossLift, 0))
			* CFrame.fromEulerAnglesXYZ(0, math.rad(math.random(-180, 180)), bossTilt)
		for _,c in ipairs(part:GetChildren()) do
			if c:IsA("BasePart") then c.CFrame = part.CFrame * c.CFrame end
		end
		-- AddBossCharacter(part, def) -- parked for later: boss limb/face system kept, visuals disabled
		AddShadow(part, part.Size.X * 0.72, point.Y)
	end

	--.. menace
	local glow = Instance.new("PointLight")
	glow.Color = def.Glow or Color3.fromRGB(255, 60, 60)
	glow.Range = 24
	glow.Brightness = 1.2
	glow.Parent = part

	local bar, hpLabel = BuildBillboard(part, def, maxHP)
	local bb = part:FindFirstChild("HPBar")
	if bb then
		bb.Size = UDim2.new(0, 260, 0, 80)
		bb.MaxDistance = def.Mobile and math.huge or 250
		if def.Mobile then
			--.. the standing body is rotated 90°, so BuildBillboard's local-frame
			--.. world offset points sideways and turns with the boss; screen-space
			--.. StudsOffset is always straight up, clear of the head
			bb.StudsOffsetWorldSpace = Vector3.zero
			bb.StudsOffset = Vector3.new(0, part.Size.X * 0.5 + 8, 0)
		end
	end

	local click = Instance.new("ClickDetector")
	click.MaxActivationDistance = 100
	click.Parent = part
	click.MouseClick:Connect(function(Player)
		OnClicked(Player, part)
	end)

	Breakables[part] = {
		Type = def;
		HP = maxHP;
		MaxHP = maxHP;
		Zone = zone;
		Bar = bar;
		HPLabel = hpLabel;
		Damagers = {};
		Holder = bossModel or part; -- kill/recycle destroys the whole rig for mobile bosses
		ChunkColor = part.Color;
	}

	local holder = bossModel or part
	holder.Parent = folder
	if bossModel then
		StartBossBrain(part, bossModel, point)
	end
	-- The biome travel popup observes BossActive; no duplicate notification toast.

	--.. it escapes if the server can't finish it
	task.delay(BOSS_TIMEOUT, function()
		local data = Breakables[part]
		if data then
			Breakables[part] = nil
			for plr, target in pairs(Targets) do
				if target == part then Targets[plr] = nil end
			end
			--.. damage is NEVER wasted: an escaped boss still pays each damager
			--.. at the same 6x per-HP rate a kill would have
			local econ = Doors[zone] and Doors[zone].Orbs or {Orb = 1, Multi = 1}
			local perHP = (def.Reward * econ.Orb * econ.Multi * 6) / math.max(1, data.MaxHP)
			local CurrencyHandler = ServerController.GetModule("CurrencyHandler")
			for plr, dmg in pairs(data.Damagers) do
				if plr.Parent == Players and dmg > 0 then
					local amount = math.max(1, math.floor(dmg * perHP))
					CurrencyHandler.AddCurrency({Player = plr; Currency = "Cucumbers"; HasTotal = true; Amount = amount;})
					--.. notif shows the post-multiplier amount the player actually receives
					local shown = CurrencyHandler.GetMulipliers({Player = plr; Currency = "Cucumbers"; Amount = amount})
					Network:FireClient(plr, "Notif", {Message = ("%s ESCAPED! +%d CUKES"):format(def.Name, shown); Type = "Success";})
				end
			end
			local meter = BossProgress[zone]
			if meter then
				meter.Value = 0
				meter:SetAttribute("BossActive", false)
				meter:SetAttribute("BossHP", 0)
				meter:SetAttribute("BossMaxHP", 0)
			end
			local escapedHolder = data.Holder or part
			escapedHolder:Destroy() -- for a mobile boss this is the whole walking rig
			Network:FireAllClients("Notif", {Message = ("%s ESCAPED!"):format(def.Name); Type = "Error";})
		end
	end)
end


