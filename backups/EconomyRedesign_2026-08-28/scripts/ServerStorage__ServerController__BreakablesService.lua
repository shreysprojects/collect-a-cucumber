				if stroke then
					stroke.Color = typeDef.Golden and Color3.fromRGB(120, 85, 0) or Color3.fromRGB(25, 70, 20)
				end
			end
		end
	end
	if not bar or not hpLabel then
		if billboard then billboard:Destroy() end
		bar, hpLabel = BuildBillboard(part, typeDef, maxHP)
	end

	if not part:FindFirstChildOfClass("ClickDetector") then
		local click = Instance.new("ClickDetector")
		click.MaxActivationDistance = 70 -- generous affordance; true per-pickaxe reach enforced in InRange
		click.Parent = part
		click.MouseClick:Connect(function(Player)
			OnClicked(Player, part)
		end)
	end

	-- One detector on the consolidated root handles the entire sliced cucumber.

	local entry = {
		Type = typeDef;
		HP = maxHP;
		MaxHP = maxHP;
		Zone = zoneName;
		Bar = bar;
		HPLabel = hpLabel;
		Damagers = {};
		Hits = 0;
		Holder = part;
		PoolKey = poolKey;
		ChunkColor = part.Color;
	}

	--.. today's mutation: rare, loud, worth 25x. The old guard excluded golden,
	--.. sliced and biome cucumbers; every type is eligible now.
	local force = MUTATIONS.ForceNext
	if force and force.Zone == zoneName then
		MUTATIONS.ForceNext = nil
		ApplyMutation(part, part, entry, force.Mut)
	elseif math.random() < MUTATIONS.Prismatic.Chance then
		ApplyMutation(part, part, entry, MUTATIONS.Prismatic)
	elseif math.random() < MUTATION_CHANCE then
		ApplyMutation(part, part, entry)
	end

	Breakables[part] = entry
	BreakablesService.TrackAdded(entry)

	part.Parent = Container[zoneName]
end

