local function ZoneAtPosition(position)
	local spawnAreas = workspace:FindFirstChild("SpawnArea")
	if not spawnAreas then return nil end
	for index, zoneName in ipairs(ZONES) do
		local region = spawnAreas:FindFirstChild(tostring(index))
		if region and region:IsA("BasePart") then
			local localPosition = region.CFrame:PointToObjectSpace(position)
			if math.abs(localPosition.X) <= region.Size.X * 0.5
				and math.abs(localPosition.Z) <= region.Size.Z * 0.5
				and localPosition.Y >= -35
				and localPosition.Y <= 175
			then
				return zoneName
			end
		end
	end
	return nil
end

local function NearestZone(position)
	local spawnAreas = workspace:FindFirstChild("SpawnArea")
	if not spawnAreas then return nil end
	local bestZone, bestDistance
	for index, zoneName in ipairs(ZONES) do
		local region = spawnAreas:FindFirstChild(tostring(index))
		if region and region:IsA("BasePart") then
			local localPosition = region.CFrame:PointToObjectSpace(position)
			local dx = math.max(math.abs(localPosition.X) - region.Size.X * 0.5, 0)
			local dz = math.max(math.abs(localPosition.Z) - region.Size.Z * 0.5, 0)
			local distance = Vector2.new(dx, dz).Magnitude
			if not bestDistance or distance < bestDistance then
				bestZone, bestDistance = zoneName, distance
			end
		end
	end
	return bestZone
end

--.. One lightning bolt picks a plain live cucumber in this biome and charges
--.. it into a variable-multiplier CHARGED cucumber. (Diamond left the storm
--.. 2026-08-27, user call: it spawn-rolls as a MATERIAL now, like golden.)
function BreakablesService.LightningStrike(zoneName)
	local candidates = {}
	local liveJackpots = 0
	for part, data in pairs(Breakables) do
		if data.Zone == zoneName and part.Parent then
			if data.Lightning then
				liveJackpots += 1
			elseif not data.Type.Boss and not data.Mutation then
				candidates[#candidates + 1] = part
			end
		end
	end
	--.. per-zone jackpot cap: never stack a second charged in the same biome
	if liveJackpots >= LIGHTNING_CAP.MaxActive then return false end
	if #candidates == 0 then return false end

	local part = candidates[math.random(#candidates)]
	local data = Breakables[part]
	local mult = RollLightningMult(zoneName, data.Type)
	local color = LIGHTNING_COLOR
	local title = "\u{26A1} CHARGED CUCUMBER"
	data.Lightning = mult

	--.. Recolour the full assembly, including model-based cucumbers, then add a
	--.. readable sparkle/light treatment at the authoritative hitbox.
	local holder = data.Holder or part
	for _, descendant in ipairs(holder:GetDescendants()) do
		if descendant:IsA("BasePart") and descendant.Name ~= "Shadow" then
			descendant.Color = color
			if isDiamond and descendant.Name ~= "Hitbox" then descendant.Material = Enum.Material.Glass end
		end
	end
	if holder:IsA("BasePart") then
		holder.Color = color
		if isDiamond then holder.Material = Enum.Material.Glass end
	end
	part.Color = color
	data.ChunkColor = color

	-- The persistent sparkle/light is client-local and budgeted. This prevents every
	-- streamed jackpot across the map from becoming a permanent mobile GPU light.
	local effectColor = isDiamond and Color3.fromRGB(235, 255, 255) or Color3.fromRGB(160, 220, 255)
	BreakablesService.MarkMutationVisual(part, effectColor, 16, 1.6)

	local bb = part:FindFirstChild("HPBar")
	if bb then
		for _, label in ipairs(bb:GetDescendants()) do
			if label:IsA("TextLabel") and not label.Text:find("/") then
				label.Text = title
				label.TextColor3 = color
			end
		end
	end

	--.. unclaimed jackpots fizzle after LIGHTNING_LIFETIME: same removal steps as
	--.. PruneZone, so counters stay exact and the population loop respawns a plain
	--.. cucumber. One grace extension if someone already damaged it (never yank a
	--.. jackpot mid-fight), then it despawns regardless.
	local function Fizzle()
		if Breakables[part] ~= data then return end -- already broken or recycled
		if not data.Lightning then return end
		if not data.FizzleGrace and data.Damagers and next(data.Damagers) ~= nil then
			data.FizzleGrace = true
			task.delay(LIGHTNING_CAP.Lifetime, Fizzle)
			return
		end
		Breakables[part] = nil
		BreakablesService.TrackRemoved(data)
		for Player, target in pairs(Targets) do
			if target == part then Targets[Player] = nil end
		end
		RecycleBreakable(part, data)
	end
	task.delay(LIGHTNING_CAP.Lifetime, Fizzle)

	--.. Bolt presentation remains biome-local.
	for _, plr in ipairs(Players:GetPlayers()) do
		local hrp = plr.Character and plr.Character:FindFirstChild("HumanoidRootPart")
		local plrZone = hrp and (ZoneAtPosition(hrp.Position) or NearestZone(hrp.Position))
		if plrZone == zoneName then
			Network:FireClient(plr, "LightningStrike", {
				Position = part.Position;
				Size = part.Size.Magnitude;
				Mult = mult;
			})
		end
	end
	return true, isDiamond and "Diamond" or "Charged"
end

--.. ADMIN: force-kill a zone's live boss through the normal Break() path
--.. (rewards/shards/meter reset all run), crediting `plr` with all the damage.
--.. Returns false when that zone has no boss up.
function BreakablesService.KillBoss(zoneName, plr)
	for part, data in pairs(Breakables) do
		if data.Type.Boss and data.Zone == zoneName and part.Parent then
			local fullDamage = math.max(1, tonumber(data.MaxHP) or 1)
			data.HP = 0
			data.Hits = math.max(1, data.Hits or 0)
			if plr and plr.Parent == Players then
				data.LastAttacker = plr
				data.Damagers = {[plr] = fullDamage}
				data.PetDamagers = {}
			end
			Break(part, data)
			return true
		end
	end
	return false
end

local function RefreshAutoFarmZone(plr)
	local character = plr.Character
	local hrp = character and character:FindFirstChild("HumanoidRootPart")
	if not hrp then return LastAutoFarmZone[plr] end
	local current = ZoneAtPosition(hrp.Position)
	if current then
		LastAutoFarmZone[plr] = current
	elseif not LastAutoFarmZone[plr] then
		-- A reconnect can place the character in a doorway between regions before
		-- the server has observed a biome. Seed the remembered area from the nearest one.
		LastAutoFarmZone[plr] = NearestZone(hrp.Position)
	end
	local remembered = LastAutoFarmZone[plr]
	if remembered then
		plr:SetAttribute("AutoFarmArea", remembered)
	end
	return remembered
end

-- Normal free chaining remains local. Autofarm owners instead chain through every
-- live cucumber in their current (or most recently visited) biome with no range cap.
RetargetNearest = function(plr)
	if EquippedPets(plr) <= 0 then return end
	local char = plr.Character
	local hrp = char and char:FindFirstChild("HumanoidRootPart")
	if not hrp then return end

	local autoFarm = IsAutoFarmEnabled(plr)
	local farmZone = autoFarm and RefreshAutoFarmZone(plr) or nil
	if autoFarm and not farmZone then return end

	local best, bestDist
	for part, data in pairs(Breakables) do
		if not autoFarm or data.Zone == farmZone then
			local d = (hrp.Position - part.Position).Magnitude
			if (autoFarm or d <= CHAIN_RANGE) and (not bestDist or d < bestDist) then
				best, bestDist = part, d
			end
		end
	end
	if best then Commit(plr, best) end
end

function BreakablesService.ToggleAutoFarm(plr)
	local owns = plr:GetAttribute("OwnsAutofarm") == true
	if not owns then
		owns = ProductController.CheckGamepass(plr, "Autofarm") == true
		if owns then plr:SetAttribute("OwnsAutofarm", true) end
	end
	if not owns then return false end

	local enabled = plr:GetAttribute("AutoFarmEnabled") ~= true
	plr:SetAttribute("AutoFarmEnabled", enabled)
	if enabled then
		RefreshAutoFarmZone(plr)
		Targets[plr] = nil
		NextAuto[plr] = 0
		RetargetNearest(plr)
	else
		Targets[plr] = nil
		NextAuto[plr] = nil
		local playerData = plr:FindFirstChild("PlayerData")
		local autoTarget = playerData and playerData:FindFirstChild("AutoTarget")
		if autoTarget then autoTarget.Value = nil end
	end

	Network:FireClient(plr, "Notif", {
		Message = enabled and "AUTOFARM ON!"
			or "AUTOFARM OFF!";
		Type = enabled and "Success" or "Error";
	})
	return enabled
end

--.. Both the ClickDetector and the client request can report the same physical click.
--.. Route both through this function and use a tiny shared gate so one click is one hit.
function BreakablesService.PickaxeStrike(Player, part, indirect)
	local data = Breakables[part]
	if not data then return end
	--.. LOCKED-BIOME GUARD (2026-08-27): strikes only land in biomes the player
	--.. has unlocked -- pickaxe reach + auto-aim could poach across borders.
	--.. (Function-scope only: this module is AT the 200 top-level-local limit.)
	local lockedZone = data.Zone
	if lockedZone and lockedZone ~= "Spawn" then
		local pd = Player:FindFirstChild("PlayerData")
		local doors = pd and pd:FindFirstChild("Doors")
		local owned = doors and doors:FindFirstChild("OwnedString")
		local hay = " # " .. ((owned and owned.Value) or "Spawn") .. " # "
		if not hay:find(" # " .. lockedZone .. " # ", 1, true) then return end
	end
	if not InRange(Player, part) then
		-- beyond swing reach but a deliberate click: commit the target so pets go work
		-- on it instead of silently eating the click (parity with OnClicked, 2026-08-22;
		-- 55 inlined -- this module's top-level scope is at Luau's 200-local limit).
		-- Fixes the post-autofarm dead bubble: autofarm clears everything near you, the
		-- respawns land far away, and every click looked like it did nothing.
		local char = Player.Character
		local hrp = char and char:FindFirstChild("HumanoidRootPart")
		if hrp and (hrp.Position - part.Position).Magnitude <= 55 then
			LastClick[Player] = os.clock()
			Commit(Player, part, false)
		end
		return
	end

	local now = os.clock()
	if now < (PickaxeReady[Player] or 0) then return end
	PickaxeReady[Player] = now + MANUAL_HIT_DEBOUNCE
	LastClick[Player] = now

	Commit(Player, part, true) -- an accepted strike counts toward the pet retarget grace

	--.. Indirect strike = the client clicked ANYWHERE and auto-aimed the nearest
	--.. in-reach breakable. Flat base damage, and the combo is neither built,
	--.. refreshed nor broken -- combo stays the reward for clicking the cucumber
	--.. itself. (Same debounce/reach/knockback as a direct hit; combo=nil keeps
	--.. the client from showing a combo popup.)
	if indirect == true then
		ApplyDamage(Player, part, math.floor(PickaxeDamageOf(Player) * WEAKPOINT_MULT), true, nil)
		BossKnockback(Player, part, data)
		return
	end

	-- Genuine rapid clicks build the combo; the shared debounce filters duplicate reports.
	if now <= (ComboExpire[Player] or 0) then
		Combo[Player] = (Combo[Player] or 0) + 1
	else
		Combo[Player] = 1
	end
	ComboExpire[Player] = now + COMBO_WINDOW
	local combo = Combo[Player]
	local mult = math.min(WEAKPOINT_MULT + (combo - 1) * COMBO_STEP, COMBO_MAX_MULT)
	ApplyDamage(Player, part, math.floor(PickaxeDamageOf(Player) * mult), true, combo)
	BossKnockback(Player, part, data)
end

-- A click on a DISTANT cucumber (up to 55 studs, inlined below because this module's
-- top-level scope is AT Luau's 200-local register limit -- a new `local` here breaks the
-- whole module from loading) can't swing the pickaxe, but it still commits the target so
-- your pets run over and work on it (AUTO_LEASH is 110, so pets happily go). Before
-- 2026-08-22 a beyond-reach click was ignored entirely even though the ClickDetector
-- cursor lit up at 70 studs -- every click should DO something.
local function OnClicked(Player, part)
	local data = Breakables[part]
	if not data then return end
	local char = Player.Character
	local hrp = char and char:FindFirstChild("HumanoidRootPart")
	if not hrp or (hrp.Position - part.Position).Magnitude > 55 then return end
	--.. LOCKED-BIOME GUARD (2026-08-27): clicking a locked-zone cucumber must
	--.. not commit pets to it either (same rule as PickaxeStrike above)
	local lockedZone = data.Zone
	if lockedZone and lockedZone ~= "Spawn" then
		local pd = Player:FindFirstChild("PlayerData")
		local doors = pd and pd:FindFirstChild("Doors")
		local owned = doors and doors:FindFirstChild("OwnedString")
		local hay = " # " .. ((owned and owned.Value) or "Spawn") .. " # "
		if not hay:find(" # " .. lockedZone .. " # ", 1, true) then return end
	end

	-- The client PickaxeStrike request is the sole damage/combo source. ClickDetector
	-- only commits the target, preventing its delayed event from becoming a second hit.
	LastClick[Player] = os.clock()
	--.. ClickDetector fires alongside the raycast click for the same physical tap,
	--.. so it must NOT advance the retarget counter (the strike itself does)
	Commit(Player, part, false)
end

