-- Pure contribution calculation used by Break() and runtime verification.
-- Any player who dealt positive damage receives at least one cucumber, even
-- when another player dealt nearly all of the damage.
function BreakablesService.ContributionReward(totalReward, damage, totalDamage)
	if type(totalReward) ~= "number" or type(damage) ~= "number" or type(totalDamage) ~= "number" then
		return 0
	end
	if totalReward <= 0 or damage <= 0 or totalDamage <= 0 then
		return 0
	end
	return math.max(1, math.floor(totalReward * (damage / totalDamage)))
end

local RetargetNearest -- defined below Commit; forward-declared so Break can chain pets onward

--.. Spend every complete set of 10 shards in one zone's bucket, forging that boss's pet each
--.. time. Returns how many were forged. Used both for the boss you just killed AND for the
--.. legacy ColossalShards pool migrated into the Spawn bucket, so a backlog cashes in at once
--.. instead of sitting there until you happen to kill that particular boss.
local function ForgeBossPets(plr, profile, Zone)
	local PetName = BOSS_PETS[Zone]
	if not PetName or not profile.BossShards then return 0 end

	local Forged = 0
	while (profile.BossShards[Zone] or 0) >= SHARDS_PER_PET do
		profile.BossShards[Zone] -= SHARDS_PER_PET
		Forged += 1
	end

	if Forged > 0 then
		local PetService = ServerController.GetModule("PetService")
		for _ = 1, Forged do
			task.spawn(PetService.AddPetToPlayer, {Player = plr; Pet = PetName})
		end

		local Message = (Forged == 1)
			and ("\u{1F996} %s FORGED!"):format(string.upper(PetName))
			or ("\u{1F996} %d %s PETS FORGED!"):format(Forged, string.upper(PetName))

		Network:FireClient(plr, "Notif", {Message = Message; Type = "Success";})
		Network:FireOtherClients(plr, "Notif", {Message = ("\u{1F996} %s FORGED %s!"):format(string.upper(plr.Name), string.upper(PetName)); Type = "Success";})
	end

	return Forged
end

--.. Manual forge, called by the Shards menu's FORGE button. Spends one complete set of
