RefreshBossExpression = function(part, data, hitMood)
	if not data or not data.Type or not data.Type.Boss then return end
	if hitMood then
		SetBossExpression(part, hitMood)
		task.delay(0.55, function()
			local live = Breakables[part]
			if live then RefreshBossExpression(part, live) end
		end)
		return
	end

	local frac = math.clamp(data.HP / data.MaxHP, 0, 1)
	if frac <= 0 then
		SetBossExpression(part, "Defeated")
	elseif frac < 0.18 then
		SetBossExpression(part, "Tired")
	elseif frac < 0.5 then
		SetBossExpression(part, "Angry")
	else
		SetBossExpression(part, "Idle")
	end
end

BossKnockback = function(Player, part, data)
	if not data or not data.Type or not data.Type.Boss then return end
	data.KnockbackReady = data.KnockbackReady or {}
	local now = os.clock()
	if now < (data.KnockbackReady[Player] or 0) then return end
	data.KnockbackReady[Player] = now + BOSS_KNOCKBACK_COOLDOWN

	local char = Player.Character
	local hrp = char and char:FindFirstChild("HumanoidRootPart")
	local humanoid = char and char:FindFirstChildOfClass("Humanoid")
	if not hrp then return end

	local offset = hrp.Position - part.Position
	local direction = offset.Magnitude > 0.1 and offset.Unit or Vector3.new(0, 0, 1)
	local velocity = direction * BOSS_KNOCKBACK_FORCE + Vector3.new(0, BOSS_KNOCKBACK_UP, 0)
	hrp.AssemblyLinearVelocity = velocity

	local shove = Instance.new("BodyVelocity")
	shove.Name = "BossKnockback"
	shove.MaxForce = Vector3.new(90000, 90000, 90000)
	shove.P = 2500
	shove.Velocity = velocity
	shove.Parent = hrp
	game:GetService("Debris"):AddItem(shove, 0.28)

	--.. strike retaliation stays a light stumble — full ragdoll on EVERY pickaxe
	--.. hit made farming the boss unplayable (user feedback). The real ragdoll is
	--.. reserved for the dodgeable attacks: slam AOE + charge trample (FlingPlayer).
	if humanoid then humanoid:ChangeState(Enum.HumanoidStateType.FallingDown) end
	RefreshBossExpression(part, data, "Hurt")
end


--.. Scale a consolidated part assembly without letting WeldConstraints drag its
--.. authoritative root away from the visible cucumber. Welded children are
--.. rebuilt around their scaled offsets, and the real rotated visual bottom is
--.. preserved so repeated event start/stop cycles cannot sink the root.
local function SetPartAssemblyScale(part, desiredScale)
	if not part or not part:IsA("BasePart") then return end
	local previousScale = tonumber(part:GetAttribute("EventVisualScale")) or 1
	if math.abs(previousScale - desiredScale) < 0.001 then return end
	local factor = desiredScale / previousScale
	local rootCFrame = part.CFrame
	local states = {}
	local welds = {}

	local function verticalHalfExtent(item)
		local cf, size = item.CFrame, item.Size
		return math.abs(cf.RightVector.Y) * size.X * 0.5
			+ math.abs(cf.UpVector.Y) * size.Y * 0.5
			+ math.abs(cf.LookVector.Y) * size.Z * 0.5
	end

	local function remember(item)
		states[#states + 1] = {
			Part = item;
			Size = item.Size;
			Relative = rootCFrame:ToObjectSpace(item.CFrame);
			CountsForBottom = item.Name ~= "Shadow";
		}
	end

	remember(part)
	for _, child in ipairs(part:GetDescendants()) do
		if child:IsA("BasePart") then
			remember(child)
		elseif child:IsA("WeldConstraint") then
			welds[#welds + 1] = {
				Name = child.Name;
				Parent = child.Parent;
				Part0 = child.Part0;
				Part1 = child.Part1;
			}
			child:Destroy()
		end
	end

	local originalBottom = math.huge
	for _, state in ipairs(states) do
		if state.CountsForBottom then
			originalBottom = math.min(originalBottom, state.Part.Position.Y - verticalHalfExtent(state.Part))
		end
	end

	for _, state in ipairs(states) do
		local item = state.Part
		item.Size = state.Size * factor
		item.CFrame = rootCFrame
			* CFrame.new(state.Relative.Position * factor)
			* state.Relative.Rotation
	end

	local scaledBottom = math.huge
	for _, state in ipairs(states) do
		if state.CountsForBottom then
			scaledBottom = math.min(scaledBottom, state.Part.Position.Y - verticalHalfExtent(state.Part))
		end
	end
	local offset = Vector3.new(0, originalBottom - scaledBottom, 0)
	if math.abs(offset.Y) > 0.001 then
		for _, state in ipairs(states) do state.Part.CFrame += offset end
	end

	for _, saved in ipairs(welds) do
		if saved.Parent and saved.Part0 and saved.Part1 then
			local weld = Instance.new("WeldConstraint")
			weld.Name = saved.Name
			weld.Part0 = saved.Part0
			weld.Part1 = saved.Part1
			weld.Parent = saved.Parent
		end
	end
	part:SetAttribute("EventVisualScale", desiredScale)
end

local function SetBreakableVisualScale(data, desiredScale)
	if not data or data.Type.Boss then return end
	local holder = data.Holder
	if holder and holder:IsA("Model") then
		local previousScale = tonumber(holder:GetAttribute("EventVisualScale")) or 1
		if math.abs(previousScale - desiredScale) >= 0.001 then
			local beforeCFrame, beforeSize = holder:GetBoundingBox()
			local beforeBottom = beforeCFrame.Position.Y - beforeSize.Y * 0.5
			holder:ScaleTo(holder:GetScale() * (desiredScale / previousScale))
			local afterCFrame, afterSize = holder:GetBoundingBox()
			local afterBottom = afterCFrame.Position.Y - afterSize.Y * 0.5
			holder:PivotTo(holder:GetPivot() + Vector3.new(0, beforeBottom - afterBottom, 0))
			holder:SetAttribute("EventVisualScale", desiredScale)
		end
	elseif holder and holder:IsA("BasePart") then
		SetPartAssemblyScale(holder, desiredScale)
	end
end

--.. ============ GOLDEN + MUTATION ARE MODIFIERS, NOT TYPES (2026-08-20) ============
--.. "Golden Cucumber" used to be its own entry in the spawn pool, so the ONLY
--.. cucumber that could ever be golden was that one shape. Golden is now a roll
--.. applied on top of WHATEVER type was picked, so a golden vined/flowered/tree/
--.. slice all exist. Mutation had the same problem plus a worse one: its code
--.. lived only in the procedural branch, so Template types (every Spawn cucumber
--.. and every Cucumber Tree) could never mutate at all. Both are applied here,
--.. from one place, for both the model and the procedural spawn paths.
local GOLDEN_CHANCE = 0.08 -- per non-boss spawn; roughly matches the old type weight
local GOLDEN_HOUR_MULT = 4 -- Golden Hour multiplies the CHANCE now (it used to triple a weight)
local GOLDEN_HP_MULT = 2.5 -- mirrors the old Golden Cucumber being ~3x a basic one
local GOLDEN_REWARD_MULT = 7
local GOLDEN_COIN_MULT = 10
local GOLDEN_COLOR = Color3.fromRGB(255, 200, 30)

--.. memoised so a golden variant is one stable table per base type rather than a
--.. fresh allocation on every spawn
local GoldenVariants = setmetatable({}, {__mode = "k"})
local function GoldenVariant(typeDef)
	local cached = GoldenVariants[typeDef]
	if cached then return cached end
	local golden = {}
	for k, v in pairs(typeDef) do golden[k] = v end
	golden.Golden = true
	golden.Name = "Golden " .. typeDef.Name
	golden.HP = math.max(1, math.floor(typeDef.HP * GOLDEN_HP_MULT))
	golden.Reward = typeDef.Reward * GOLDEN_REWARD_MULT
	golden.BonusCoins = math.floor((typeDef.BonusCoins or 0) * GOLDEN_COIN_MULT)
	GoldenVariants[typeDef] = golden
	return golden
end

local function GoldenChanceFor(zoneName)
	return GOLDEN_CHANCE * (IsEventActive(zoneName, "GoldenHour") and GOLDEN_HOUR_MULT or 1)
end

--.. paints a whole assembly gold. Works on a procedural root Part (children) and
--.. on a Template Model alike; the invisible Hitbox is tinted too because it is
--.. what Break() falls back to for the break-chunk colour.
local function ApplyGoldenLook(holder)
	for _, d in ipairs(holder:GetDescendants()) do
		if d:IsA("BasePart") and d.Name ~= "Shadow" then
			d.Color = GOLDEN_COLOR
			if d.Name ~= "Hitbox" then d.Material = Enum.Material.Foil end
		end
	end
	if holder:IsA("BasePart") then holder.Color = GOLDEN_COLOR end
end

