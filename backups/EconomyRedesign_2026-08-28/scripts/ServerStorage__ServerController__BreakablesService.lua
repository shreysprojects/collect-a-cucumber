		if shadow and shadow:IsA("BasePart") then
			shadow.CFrame = CFrame.new(part.Position.X, point.Y + 0.06, part.Position.Z) * CFrame.Angles(0, 0, math.rad(90))
		else
			AddShadow(part, 3.2, point.Y)
		end
	else
		local oldRootCFrame = part.CFrame
		--.. rest the body ON the ground: lowest point of the 8-degree tipped
		--.. cylinder is half the diameter plus the dipped cap end
		local tilt = math.rad(8)
		local lift = part.Size.Y * 0.5 * math.cos(tilt) + part.Size.X * 0.5 * math.sin(tilt) + 0.05
		local newRootCFrame = CFrame.new(point + Vector3.new(0, lift, 0))
			* CFrame.fromEulerAnglesXYZ(0, math.rad(math.random(-180, 180)), tilt)
		part.CFrame = newRootCFrame
		-- Welds are inert while pooled outside Workspace, so move decorations by
		-- the root delta on reuse. Fresh builds still contain origin-space offsets.
		local delta = newRootCFrame * oldRootCFrame:Inverse()
		for _,c in ipairs(part:GetChildren()) do
			if c:IsA("BasePart") then
				c.CFrame = wasPooled and (delta * c.CFrame) or (newRootCFrame * c.CFrame)
			end
		end
		local shadow = part:FindFirstChild("Shadow")
		if shadow and shadow:IsA("BasePart") then
			shadow.CFrame = CFrame.new(part.Position.X, point.Y + 0.06, part.Position.Z) * CFrame.Angles(0, 0, math.rad(90))
		else
			AddShadow(part, part.Size.X * 0.72, point.Y)
