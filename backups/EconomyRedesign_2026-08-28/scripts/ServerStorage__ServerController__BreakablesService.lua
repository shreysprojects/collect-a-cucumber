--.. today's mutation: rare, loud, worth 25x. `holder` is the model or root part,
--.. `root` is the part the HP bar / Breakables key hangs off.
local function ApplyMutation(holder, root, entry, mutOverride)
	local mut = mutOverride or TodaysMutation()
	entry.Mutation = mut.Name
	for _, d in ipairs(holder:GetDescendants()) do
		if d:IsA("BasePart") and d.Name ~= "Shadow" then d.Color = mut.Color end
	end
	if holder:IsA("BasePart") then holder.Color = mut.Color end
	entry.ChunkColor = mut.Color

	--.. PRISMATIC bodies hue-cycle live: rare enough (1-in-30k) that a lazy
	--.. server loop over the few live parts is negligible; dies with the model
	if mut.Name == "PRISMATIC" then
		local parts = {}
		for _, d in ipairs(holder:GetDescendants()) do
			if d:IsA("BasePart") and d.Name ~= "Shadow" then parts[#parts + 1] = d end
		end
		if holder:IsA("BasePart") then parts[#parts + 1] = holder end
		task.spawn(function()
			local t0 = os.clock()
			while root.Parent do
				local c = Color3.fromHSV((os.clock() - t0) * 0.22 % 1, 0.6, 1)
				for _, p in ipairs(parts) do
					if p.Parent then p.Color = c end
				end
				task.wait(0.15)
			end
		end)
	end

	-- Persistent mutation effects are rendered locally with proximity and mobile
	-- budgets; the server replicates only this lightweight visual descriptor.
	BreakablesService.MarkMutationVisual(root, mut.Color, 14, 1.4)

	--.. retitle the billboard so it reads e.g. "NEON VINED CUCUMBER"
	local bb = root:FindFirstChild("HPBar")
	if bb then
		for _, l in ipairs(bb:GetDescendants()) do
			if l:IsA("TextLabel") and not l.Text:find("/") then
				l.Text = mut.Name .. " " .. l.Text
				l.TextColor3 = mut.Color
			end
		end
	end
end

--.. VAULT RESTORE RE-SKIN (2026-08-28): a rejoining owner's stored cucumbers
--.. are rebuilt from CLEAN templates (CarryService.BuildFromTemplate), which
--.. lost every baked-in look -- mutated records showed a plain body under a
--.. card + shimmer that still read the saved Mutation tag ("just sparkles").
--.. Re-applies, in spawn order: material prefixes parsed off the SAVED name
--.. ("Diamond "/"Golden ", exclusive at spawn but parsed independently),
--.. then the rotation/PRISMATIC/CHARGED recolor from the Mutation tag on
--.. top. Legacy tags map across renames (FROSTED/BLAZING) and eras
--.. (Mutation="DIAMOND" pre-demotion saves get the diamond skin). Static
--.. colors only -- no live hue-cycle for PRISMATIC, matching what a fresh
--.. organic deposit looks like on the podium.
function BreakablesService.ApplyStoredLook(model, savedName, mutationName)
	if typeof(model) ~= "Instance" then return end
	--.. saved names can stack prefixes ("Charged Golden ..."-style); strip
	--.. like LoadVault's FindType retry does, noting what came off
	local rest = tostring(savedName or ""):lower()
	local isDiamond, isGolden = false, false
	local changed = true
	while changed do
		changed = false
		local r = rest:gsub("^%s*golden%s+", "")
		if r ~= rest then isGolden = true rest = r changed = true end
		r = rest:gsub("^%s*diamond%s+", "")
		if r ~= rest then isDiamond = true rest = r changed = true end
		r = rest:gsub("^%s*charged%s+", "") -- charged recolors via the Mutation tag below
		if r ~= rest then rest = r changed = true end
	end
	if isDiamond then
		MUTATIONS.DiamondMod.ApplyLook(model)
	elseif isGolden then
		ApplyGoldenLook(model)
	end
	local wanted = tostring(mutationName or ""):upper()
	if wanted == "" then return end
	if wanted == "FROSTED" then wanted = "FROZEN" end -- pre-rename saves (2026-08-27)
	if wanted == "BLAZING" then wanted = "MOLTEN" end
	local mut
	for _, m in ipairs(MUTATIONS) do
		if m.Name == wanted then mut = m break end
	end
	if not mut and wanted == MUTATIONS.Prismatic.Name then mut = MUTATIONS.Prismatic end
	if not mut and wanted == "CHARGED" then mut = {Name = "CHARGED"; Color = LIGHTNING_COLOR} end
	if not mut then
		if wanted == "DIAMOND" and not isDiamond then
			--.. grandfathered records from when DIAMOND was a rotation mutation
			MUTATIONS.DiamondMod.ApplyLook(model)
		end
		return
	end
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") and d.Name ~= "Shadow" then d.Color = mut.Color end
	end
	if model:IsA("BasePart") then model.Color = mut.Color end
end

function BreakablesService.SpawnBreakable(zoneName, forceSliced)
	local template = Collectables:FindFirstChild(zoneName)
	if not template then return end

	local typeDef
	if forceSliced then
		--.. zone-aware: Spawn's sliced type is its own mesh slice, not the shared one
		typeDef = SlicedTypeFor(zoneName)
	else
		typeDef = PickType(zoneName)
	end
	if not typeDef then return end

	--.. every zone keeps at least one tree standing: it's the landmark payday.
	--.. Matched on the Tree flag (not a hardcoded template name) so a zone with
	--.. its own tree model, like Spawn's, still gets the guarantee.
	if not typeDef.Sliced and not typeDef.Tree and Container and Container[zoneName] then
		--.. The standing-tree scan matches THIS zone's tree by name, not the literal
		--.. "Cucumber Tree": a mesh biome names its landmark whatever it likes (Desert's
		--.. is "Sandstone Tree"), and a name that never matches would report "no tree"
		--.. forever and turn every regular spawn into a tree. A golden tree still counts
		--.. as the landmark, since GoldenVariant only prefixes the name.
		local treeType
		for _,t in ipairs(EffectiveTypes(zoneName)) do
			if t.Tree then treeType = t break end
		end
		if treeType then
			local goldenName = "Golden " .. treeType.Name
			local hasTree = false
			for _,b in ipairs(Container[zoneName]:GetChildren()) do
				if b.Name == treeType.Name or b.Name == goldenName then hasTree = true break end
			end
			if not hasTree then typeDef = treeType end
		end
	end
	--.. MATERIAL LAYER (diamond > golden, mutually exclusive): rolled on top of
	--.. whatever type was picked, so ANY cucumber can be diamond or golden.
	--.. Must happen before maxHP below so the HP bonus counts. Rotation
	--.. mutations roll LATER and stack on top of either material.
	if MUTATIONS.ForceDiamond == zoneName or math.random() < MUTATIONS.DiamondMod.Chance then
		MUTATIONS.ForceDiamond = nil
		typeDef = MUTATIONS.DiamondMod.VariantOf(typeDef)
	elseif math.random() < GoldenChanceFor(zoneName) then
		typeDef = GoldenVariant(typeDef)
	end

	--.. later zones = tougher produce, so endgame pets don't one-shot the world
	local hpMult = ZONE_HP[zoneName] or 1
	local superStrengthActive = IsEventActive(zoneName, "SuperStrength")
	local maxHP = math.floor(typeDef.HP * hpMult)

	--.. Model templates (Cucumber Tree etc.) take their own path
	if typeDef.Template then
		local Templates = Assets:FindFirstChild("BreakableModels")
		local modelTemplate = Templates and Templates:FindFirstChild(typeDef.Template)
		if not modelTemplate then return end

		local model = modelTemplate:Clone()
		model.Name = typeDef.Name
		-- All non-boss, non-sliced breakables are 75% of their original visual size.
		model:ScaleTo(model:GetScale() * 0.75 * (superStrengthActive and 2 or 1))
		model:SetAttribute("EventVisualScale", superStrengthActive and 2 or 1)
		local ext = model:GetExtentsSize()
		local point = GetZonePoint(zoneName, math.max(ext.X, ext.Z) * 0.5)
		model:PivotTo(CFrame.new(point + Vector3.new(0, ext.Y / 2, 0)) * CFrame.Angles(0, math.rad(math.random(-180, 180)), 0))

		local part = model.PrimaryPart
		local visual = model:FindFirstChild("Canopy") or model:FindFirstChild("Trunk")

		local bar, hpLabel = BuildBillboard(part, typeDef, maxHP)
		-- One detector on the unified tree hitbox replaces detectors on every visual part.
		-- The client raycast still resolves canopy/trunk clicks back to this PrimaryPart.
		local click = Instance.new("ClickDetector")
		click.MaxActivationDistance = 70
		click.Parent = part
		click.MouseClick:Connect(function(Player)
			OnClicked(Player, part)
		end)

		local entry = {
			Type = typeDef;
			HP = maxHP;
			MaxHP = maxHP;
			Zone = zoneName;
			Bar = bar;
			HPLabel = hpLabel;
			Damagers = {};
			Hits = 0;
			Holder = model;
			ChunkColor = visual and visual.Color or nil;
		}

		--.. mesh models are recoloured live (there is no BuildCucumber to bake it in)
		if typeDef.Golden then
			ApplyGoldenLook(model)
			entry.ChunkColor = GOLDEN_COLOR
		elseif typeDef.Diamond then
			MUTATIONS.DiamondMod.ApplyLook(model)
			entry.ChunkColor = MUTATIONS.DiamondMod.Color
		end
		--.. mutation used to be unreachable from this branch entirely, so no Template
		--.. breakable could ever mutate. Any type can now, golden ones included.
		local force = MUTATIONS.ForceNext
		if force and force.Zone == zoneName then
			MUTATIONS.ForceNext = nil
			ApplyMutation(model, part, entry, force.Mut)
		elseif math.random() < MUTATIONS.Prismatic.Chance then
			ApplyMutation(model, part, entry, MUTATIONS.Prismatic)
		elseif math.random() < MUTATION_CHANCE then
			ApplyMutation(model, part, entry)
		end

		Breakables[part] = entry
		BreakablesService.TrackAdded(entry)

		model.Parent = Container[zoneName]
		return
	end

	local part
	local wasPooled = false
	local poolKey
	if typeDef.Sliced then
		local pool = SlicedPool[zoneName]
		part = pool and table.remove(pool) or nil
		wasPooled = part ~= nil
		if not part then
			-- Layered cucumber slice: dark-green rind, pale flesh and five visible seeds.
			-- Decorations never intercept targeting; the rind remains the single hit part.
			part = Instance.new("Part")
			part.Shape = Enum.PartType.Cylinder
