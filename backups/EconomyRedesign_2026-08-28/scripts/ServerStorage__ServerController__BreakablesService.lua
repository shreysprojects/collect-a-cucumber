		SLICED_PER_ZONE_MAX
	)
end

local function PopulationOf(zoneName)
	local population = Population[zoneName]
	if not population then
		population = {Sliced = 0; Other = 0}
		Population[zoneName] = population
	end
	return population
end

function BreakablesService.TrackAdded(data)
	if not data or data.Type.Boss then return end
	local population = PopulationOf(data.Zone)
	if data.Type.Sliced then population.Sliced += 1 else population.Other += 1 end
end

function BreakablesService.TrackRemoved(data)
	if not data or data.Type.Boss then return end
	local population = PopulationOf(data.Zone)
	if data.Type.Sliced then
		population.Sliced = math.max(0, population.Sliced - 1)
	else
		population.Other = math.max(0, population.Other - 1)
	end
end

function BreakablesService.CountZonePopulation(zoneName)
	local population = PopulationOf(zoneName)
	return population.Sliced, population.Other
end

--.. A player's biome only unloads once they have actually ENTERED another one
--.. (user request 2026-08-21). Merely stepping outside a biome -- border land,
--.. walkways, minigame teleports -- must not drain it, so each player
--.. remembers the biome they last stood INSIDE and that anchor keeps its zone
--.. (plus neighbors) active until a different biome replaces it.
--.. module-table fields, NOT new top-level locals: this chunk already rides
--.. Lua's 200-local limit, and two more locals here broke the whole compile
--.. ("Out of local registers").
BreakablesService.LastInhabitedIndex = {} -- [player] = ZONES index of the biome they last stood inside
Players.PlayerRemoving:Connect(function(plr)
	BreakablesService.LastInhabitedIndex[plr] = nil
end)

--.. "Inside the biome" means standing on its ZoneParts SLAB (named per zone,
--.. spans the whole walkable biome: hub, egg stand, vendors), NOT the narrower
--.. SpawnArea cucumber field that ZoneAtPosition checks. Walking from a
--.. biome's field to its own egg/hub must never re-anchor or unload anything
--.. (user report 2026-08-21: "didn't leave the biome, just the spawn area").
function BreakablesService.SlabZoneAt(position)
	local zones = workspace:FindFirstChild("Zones")
	local zoneParts = zones and zones:FindFirstChild("ZoneParts")
	if not zoneParts then return nil end
	for _, slab in ipairs(zoneParts:GetChildren()) do
		if slab:IsA("BasePart") then
			local lp = slab.CFrame:PointToObjectSpace(position)
			if math.abs(lp.X) <= slab.Size.X * 0.5 + 6
				and math.abs(lp.Z) <= slab.Size.Z * 0.5 + 6
				and lp.Y >= -15 and lp.Y <= 150
			then
				return slab.Name
			end
		end
	end
	return nil
end

function BreakablesService.ActiveZones()
	local active = {}
	local zoneParts = workspace:FindFirstChild("Zones") and workspace.Zones:FindFirstChild("ZoneParts")
	if not zoneParts then return active end

	for _, Player in ipairs(Players:GetPlayers()) do
		local root = Player.Character and Player.Character:FindFirstChild("HumanoidRootPart")
		if root then
			--.. containment first: standing inside a biome (its full slab, not
			--.. just the cucumber field) commits to it; while outside every
			--.. biome the previous commitment holds unchanged
			local insideName = BreakablesService.SlabZoneAt(root.Position)
			local anchorIndex
			if insideName then
				anchorIndex = table.find(ZONES, insideName)
				BreakablesService.LastInhabitedIndex[Player] = anchorIndex
			else
				anchorIndex = BreakablesService.LastInhabitedIndex[Player]
			end

			--.. bootstrap fallback (fresh join, never stood inside a biome yet):
			--.. the old nearest-zone estimate
			if not anchorIndex then
				local nearestDistance = math.huge
				for index, zoneName in ipairs(ZONES) do
					local part = zoneParts:FindFirstChild(zoneName)
					if part and part:IsA("BasePart") then
						local distance = (Vector2.new(root.Position.X, root.Position.Z)
							- Vector2.new(part.Position.X, part.Position.Z)).Magnitude
						if distance < nearestDistance then
							nearestDistance = distance
							anchorIndex = index
						end
					end
				end
			end
			-- Populate the current area and its immediate neighbors before the player enters.
			if anchorIndex then
				for index = math.max(1, anchorIndex - 1), math.min(#ZONES, anchorIndex + 1) do
					active[ZONES[index]] = true
				end
			end
		end
	end

	-- Hysteresis prevents a biome from disappearing the instant the nearest-zone
	-- calculation flips at a border. New areas fill immediately; old ones remain
	-- warm briefly and are then drained by the paced population worker.
	local now = os.clock()
	for _, zoneName in ipairs(ZONES) do
		if active[zoneName] then
			LastActiveAt[zoneName] = now
		elseif LastActiveAt[zoneName] and now - LastActiveAt[zoneName] <= ZONE_UNLOAD_GRACE then
			active[zoneName] = true
		end
	end
	return active
end

function BreakablesService.ZoneTargets(zoneName, active)
	if active[zoneName] then
		return BreakablesService.SlicedPerZone(), BreakablesService.TargetOtherPerZone()
	end
	return EMPTY_ZONE_SLICED, EMPTY_ZONE_OTHER
end

function BreakablesService.PruneZone(zoneName, slicedTarget, otherTarget)
	local sliced, other = BreakablesService.CountZonePopulation(zoneName)
	local removed = 0
	for part, data in pairs(Breakables) do
		if removed >= PRUNE_PER_STEP then break end
		--.. never prune a lightning jackpot — charged rolls stay findable —
		--.. or a player-dropped carry (data.Carried): the field sheds a natural one
		--.. instead and settles back at target
		if data.Zone == zoneName and not data.Type.Boss and not data.Lightning and not data.Carried then
			local shouldRemove = (data.Type.Sliced and sliced > slicedTarget)
				or (not data.Type.Sliced and other > otherTarget)
			if shouldRemove then
				Breakables[part] = nil
				BreakablesService.TrackRemoved(data)
				for Player, target in pairs(Targets) do
					if target == part then Targets[Player] = nil end
				end
				RecycleBreakable(part, data)
				if data.Type.Sliced then sliced -= 1 else other -= 1 end
				removed += 1
			end
		end
	end
end



local function BuildCucumber(zoneColor, scale, golden, overrideColor, overrideMaterial, glowColor)
	--.. hand-built cartoon cucumber: ridged body, capped ends, stem + vine curl.
	--.. Root part is the click target; everything else is welded so the
	--.. client-side bob and spin carry the whole vegetable.
	local dia = 0.78 * scale
	local len = 2.35 * scale

	--.. a biome cucumber passes its own colour; otherwise use the zone's tint
	local h, s, v = (overrideColor or zoneColor):ToHSV()
	local bodyColor
	if golden then
		bodyColor = Color3.fromRGB(255, 200, 30)
	else
		bodyColor = Color3.fromHSV(h, math.clamp(s * 1.1, 0, 1), math.clamp(v * (0.9 + math.random() * 0.25), 0, 1))
	end
	--.. real cucumbers have LIGHT streaks on darker skin — pale ridges pop
	--.. nicely in cartoon lighting where dark ones read as harsh shadows
	local ridgeColor = golden and Color3.fromRGB(255, 224, 96)
		or Color3.fromHSV(h, math.clamp(s * 0.72, 0, 1), math.clamp(v * 1.25, 0, 1))
	local material = golden and Enum.Material.Foil or (overrideMaterial or Enum.Material.SmoothPlastic)

	local body = Instance.new("Part")
	body.Shape = Enum.PartType.Cylinder
	body.Size = Vector3.new(len, dia, dia)
	body.Color = bodyColor
	body.Material = material
	body.Anchored = true
	body.CanCollide = false
	body.CanTouch = false
	body.CanQuery = true
	body.CastShadow = true

	local function weldTo(inst)
		inst.Anchored = false
		inst.CanCollide = false
		inst.CanTouch = false
		inst.CanQuery = true
		inst.CastShadow = true
		inst.Parent = body
		local w = Instance.new("WeldConstraint")
		w.Part0 = body
		w.Part1 = inst
		w.Parent = inst
	end

	--.. rounded ends
	for side = -1, 1, 2 do
		local cap = Instance.new("Part")
		cap.Name = "Cap"
		cap.Shape = Enum.PartType.Ball
		cap.Size = Vector3.new(dia * 0.96, dia * 0.96, dia * 0.96)
		cap.Color = bodyColor
		cap.Material = material
		cap.CFrame = body.CFrame * CFrame.new(side * len / 2 * 0.94, 0, 0)
		weldTo(cap)
	end

	--.. lengthwise ridges (the thing that makes it read "cucumber", not "blob");
	--.. centered ON the surface so half the strip stands proud of the skin
	for i = 0, 5 do
		local theta = math.rad(i * 60 + 30)
		local ridge = Instance.new("Part")
		ridge.Name = "Ridge"
		--.. shorter than the cylinder so strips never stab through the end caps,
		--.. and low-profile so they read as soft bumps, not fins
		ridge.Size = Vector3.new(len * 0.62, dia * 0.07, dia * 0.2)
		ridge.Color = ridgeColor
		ridge.Material = material
		ridge.CFrame = body.CFrame * CFrame.Angles(theta, 0, 0) * CFrame.new(0, dia * 0.485, 0)
		weldTo(ridge)
	end

	--.. stem nub + curly vine
	local stem = Instance.new("Part")
	stem.Name = "Stem"
	stem.Shape = Enum.PartType.Cylinder
	stem.Size = Vector3.new(dia * 0.4, dia * 0.22, dia * 0.22)
	stem.Color = Color3.fromRGB(94, 92, 44)
	stem.Material = Enum.Material.SmoothPlastic
	stem.CFrame = body.CFrame * CFrame.new(len / 2 * 1.02, dia * 0.05, 0)
	weldTo(stem)

	for i = 1, 3 do
		local curl = Instance.new("Part")
		curl.Name = "Vine"
		curl.Shape = Enum.PartType.Ball
		local cs = dia * (0.18 - i * 0.035)
		curl.Size = Vector3.new(cs, cs, cs)
		curl.Color = Color3.fromRGB(70, 140, 52)
		curl.Material = Enum.Material.SmoothPlastic
		curl.CFrame = body.CFrame * CFrame.new(len / 2 * 1.02 + dia * 0.1 * i, dia * (0.1 + 0.16 * i), dia * 0.08 * i * (i % 2 == 0 and 1 or -1))
		weldTo(curl)
	end

	--.. leaf
	local leaf = Instance.new("Part")
	leaf.Name = "Leaf"
	leaf.Shape = Enum.PartType.Ball
	leaf.Size = Vector3.new(dia * 0.7, dia * 0.16, dia * 0.5)
	leaf.Color = Color3.fromRGB(52, 118, 40)
	leaf.Material = Enum.Material.Grass
	leaf.CFrame = body.CFrame * CFrame.new(len / 2 * 0.86, dia * 0.5, 0) * CFrame.Angles(0, 0, math.rad(-18))
	weldTo(leaf)

	if golden then
		local sparkle = Instance.new("ParticleEmitter")
		sparkle.Name = "GoldSparkle"
		sparkle.Color = ColorSequence.new(Color3.fromRGB(255, 220, 90))
		sparkle.LightEmission = 1
		sparkle.Rate = 4
		sparkle.Lifetime = NumberRange.new(0.8, 1.4)
		sparkle.Speed = NumberRange.new(0.5, 1.5)
		sparkle.Size = NumberSequence.new({NumberSequenceKeypoint.new(0, 0.4), NumberSequenceKeypoint.new(1, 0)})
		sparkle.Parent = body
		local glow = Instance.new("PointLight")
		glow.Color = Color3.fromRGB(255, 214, 90)
		glow.Range = 12
		glow.Brightness = 0.8
		glow.Parent = body
	end

	--.. biome glow (lava, cosmic): a coloured light so it reads from across the zone
	if glowColor then
		local glow = Instance.new("PointLight")
		glow.Color = glowColor
		glow.Range = 13
		glow.Brightness = 1.1
		glow.Parent = body
	end

	return body
end

