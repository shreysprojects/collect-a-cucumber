			flesh.Material = Enum.Material.SmoothPlastic
			flesh.CFrame = part.CFrame
			weldSliceDetail(flesh)

			local seedPositions = {
				Vector2.new(0, 0.06);
				Vector2.new(0.38, 0.28);
				Vector2.new(-0.38, 0.28);
				Vector2.new(0.3, -0.38);
				Vector2.new(-0.3, -0.38);
