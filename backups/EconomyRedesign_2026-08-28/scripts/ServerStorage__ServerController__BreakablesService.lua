-- Collect every currently spawned cucumber for a developer-product purchaser.
-- A snapshot is required because Break mutates the registry while iterating.
function BreakablesService.NukeAll(Player)
	if not Player or Player.Parent ~= Players then return 0 end
	local snapshot = {}
	for part, data in pairs(Breakables) do
		if part and part.Parent and data then
			table.insert(snapshot, {Part = part; Data = data;})
		end
	end

	local collected = 0
	for _, entry in ipairs(snapshot) do
		local part, data = entry.Part, entry.Data
		if Breakables[part] == data and part.Parent then
			local fullDamage = math.max(1, tonumber(data.MaxHP) or tonumber(data.HP) or 1)
			data.Nuke = true
			data.HP = 0
			data.Hits = math.max(1, data.Hits or 0)
			data.LastAttacker = Player
			data.Damagers = {[Player] = fullDamage}
			data.PetDamagers = {}
			Break(part, data)
			collected += 1
		end
	end
	return collected
end

RecycleBreakable = function(part, data)
    local holder = data.Holder or part

    if data.Type.Sliced and holder == part and not data.Mutation and not data.Lightning then
        part.Parent = nil
        SlicedPool[data.Zone] = SlicedPool[data.Zone] or {}
        table.insert(SlicedPool[data.Zone], part)
        return
    end

    -- Mutations/charges carry one-off recolors/effects and models are rare, so only
    -- pool the high-volume regular cucumber assemblies whose visuals are reusable.
    if holder == part and data.PoolKey and not data.Mutation and not data.Lightning then
        part.Parent = nil
        local pool = OtherPool[data.PoolKey]
        if not pool then
            pool = {}
            OtherPool[data.PoolKey] = pool
        end
        if #pool < MAX_POOL_PER_TYPE then
            table.insert(pool, part)
        else
            part:Destroy()
        end
        return
    end

    holder:Destroy()
end

local function ApplyResolvedDamage(Player, part, data, dmg, isClick, combo, crit, countEventHit)
	if Breakables[part] ~= data then return end
	data.HP -= dmg
	data.LastAttacker = Player -- used only to route the client-local destruction shake
	data.Hits = (data.Hits or 0) + 1 -- landed hits; the client plays the crunch on 2+ hit breaks
	data.Damagers[Player] = (data.Damagers[Player] or 0) + dmg
	if countEventHit and not data.Type.Boss and RecordEventHit then
		RecordEventHit(data.Zone)
	end
	-- Track passive-pet damage separately so Time Skip rates cannot be inflated by pickaxe hits.
	if not isClick then
		data.PetDamagers = data.PetDamagers or {}
		data.PetDamagers[Player] = (data.PetDamagers[Player] or 0) + dmg
	end
	UpdateBar(part)

	-- Other clients discard hit packets, so send only to the attacker.
	Network:FireClient(Player, "BreakableHit", {
		Part = part;
		Position = part.Position; -- survives replication races when a one-shot removes part
		PartSize = part.Size;
		Amount = dmg;
		Golden = data.Type.Golden == true;
		Attacker = Player.Name;
		Click = isClick == true;
		Crit = crit;
		Combo = combo; -- nil on Super Strength splash targets
		--.. rarity ladder (SFX pass 2026-08-26): nil keys don't serialize
		Mutation = data.Mutation; -- mutation-of-the-day name, or "DIAMOND"
		Charged = data.Lightning and true or nil; -- storm-charged jackpot
		Diamond = data.Type.Diamond and true or nil; -- diamond MATERIAL (spawn-rolled)
		Boss = (data.Type.Boss == true and data.Type.Mobile == true) and true or nil; -- the walking boss
	})

	if data.HP <= 0 then
		Break(part, data)
	end
end

local SUPER_STRENGTH_SPLASH_RADIUS = 10

local function ApplyDamage(Player, part, dmg, isClick, combo)
	local data = Breakables[part]
	if not data then return end
	--.. LOCKED-BIOME GUARD (2026-08-27): NO damage source -- click, PET auto
	--.. tick, or splash -- lands in a biome the player hasn't unlocked. Pets
	--.. were the leak: their auto-tick damaged locked-zone cucumbers the
	--.. strike guard already refused. Also drops the pet target so the next
	--.. retarget picks a legal cucumber. (Function scope only -- this module
	--.. is AT the 200 top-level-local limit.)
	local lockedZone = data.Zone
	if lockedZone and lockedZone ~= "Spawn" then
		local pd = Player:FindFirstChild("PlayerData")
		local doors = pd and pd:FindFirstChild("Doors")
		local owned = doors and doors:FindFirstChild("OwnedString")
		local hay = " # " .. ((owned and owned.Value) or "Spawn") .. " # "
		if not hay:find(" # " .. lockedZone .. " # ", 1, true) then
			if Targets[Player] == part then Targets[Player] = nil end
			return
		end
	end

	local superStrengthActive = IsEventActive(data.Zone, "SuperStrength")
	local superStrengthHit = isClick and superStrengthActive
	if superStrengthActive then
		dmg *= isClick and 5 or 2 -- pickaxes: 5x; passive pet strikes: 2x
	end

	--.. Crits keep long breaks spicy. Splash copies this final resolved amount.
	--.. 2026-08-27 (user): flat 10% chance for every hit -- the 25%-with-pity
	--.. click rework made crits land on a near-guaranteed schedule, not luck.
	local crit = math.random() < 0.10
	if crit then dmg *= 5 end

	local splashTargets
	if superStrengthHit then
		splashTargets = {}
		local origin = part.Position
		for otherPart, otherData in pairs(Breakables) do
			if otherPart ~= part and otherData.Zone == data.Zone and otherData.HP > 0
				and (otherPart.Position - origin).Magnitude <= SUPER_STRENGTH_SPLASH_RADIUS then
				splashTargets[#splashTargets + 1] = {Part = otherPart; Data = otherData;}
			end
		end
	end

	ApplyResolvedDamage(Player, part, data, dmg, isClick, combo, crit, true)

	--.. One-hop splash only: nearby cucumbers receive the exact resolved damage,
	--.. but do not create more splashes or count as extra landed event-goal hits.
	if splashTargets then
		for _, target in ipairs(splashTargets) do
			ApplyResolvedDamage(Player, target.Part, target.Data, dmg, true, nil, crit, false)
		end
	end
end

local PICKAXE_REACH = 30 -- studs from the cucumber's SURFACE. (10 -> 14 -> 30, 2026-08-23:
-- the melee walk-up design measurably exhausted MOBILE players -- half the audience --
-- who held the best 5-minute retention of any segment and then quit with the shortest
-- sessions: joystick-shuffle to every cucumber, then tap-tap-tap. 30 lets players pop
-- anything they can meaningfully see; positioning still matters at field scale, and
-- beyond reach a click still dispatches pets.)
--.. This replaced a pickaxe-scaled reach (20 + Stats.Radius * 3, so 41 studs on the base
--.. pickaxe). Stats.Radius itself is deliberately UNTOUCHED -- CollectionService still
--.. reads it for the orb pickup radius (CheckMagnitude: Radius * 2 + 5), so a pickaxe's
--.. +Range is still worth buying, it just no longer buys click reach.
--.. Mirrored client-side by myReach/PICKAXE_REACH in BreakablesClient; change both together.
local function ReachOf(_Player, part)
	--.. surface-relative, so a boss stays hittable from its edge instead of requiring
	--.. the player to stand inside it
	local radius = part and math.max(part.Size.X, part.Size.Z) * 0.5 or 0
	return radius + PICKAXE_REACH
end

local function InRange(Player, part)
	local char = Player.Character
	local hrp = char and char:FindFirstChild("HumanoidRootPart")
	if not hrp then return false end
	return (hrp.Position - part.Position).Magnitude <= ReachOf(Player, part)
end

--.. FRIEND BOOST: every friend you have in the server grants +10% pickaxe
--.. damage, capped at 5 friends (+50%). Counts are cached and only recomputed
--.. when the roster changes so the damage path never yields on IsFriendsWith.
local FRIEND_BOOST_PER = 0.10 -- +10% pickaxe damage per friend in-server
local FRIEND_BOOST_MAX = 5 -- capped at 5 friends
local FriendCount = {} -- [player] = friends currently in this server (capped)

local function CountFriendsInServer(Player)
	local n = 0
	for _, other in ipairs(Players:GetPlayers()) do
		if other ~= Player then
			local ok, isFriend = pcall(function()
				return Player:IsFriendsWith(other.UserId)
			end)
			if ok and isFriend then n += 1 end
		end
	end
	return math.min(n, FRIEND_BOOST_MAX)
end

local function RefreshFriendCounts()
	--.. roster changed: everyone's friend-in-server count may have shifted
	for _, plr in ipairs(Players:GetPlayers()) do
		FriendCount[plr] = CountFriendsInServer(plr)
	end
end

local function FriendBoostMult(Player)
	local n = FriendCount[Player]
	if n == nil then
		--.. not computed yet: no boost this hit, resolve in the background
		FriendCount[Player] = 0
		task.spawn(function()
			if Player.Parent == Players then
				FriendCount[Player] = CountFriendsInServer(Player)
			end
		end)
		return 1
	end
	return 1 + n * FRIEND_BOOST_PER
end

Players.PlayerAdded:Connect(function()
	task.spawn(RefreshFriendCounts)
end)
Players.PlayerRemoving:Connect(function(plr)
	FriendCount[plr] = nil
	task.defer(RefreshFriendCounts)
end)
task.spawn(RefreshFriendCounts) -- seed for anyone already in the server

local function PickaxeDamageOf(Player)
