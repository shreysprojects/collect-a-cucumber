local function Break(part, data)
	Breakables[part] = nil
	BreakablesService.TrackRemoved(data)
	for plr, target in pairs(Targets) do
		if target == part then
			local wasAutoFarm = plr:GetAttribute("OwnsAutofarm") == true
				and plr:GetAttribute("AutoFarmEnabled") == true
			Targets[plr] = nil
			-- Hand off before the destroyed model is recycled. Manual farming
			-- uses the 15-stud CHAIN_RANGE while autofarm remains biome-wide, but both
			-- paths keep AutoTarget continuously assigned between live targets so pets
			-- never receive a one-frame command to return to the player.
			RetargetNearest(plr)
		end
	end

