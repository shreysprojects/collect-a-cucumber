local function IsFarEnoughFromLastSpawn(zoneName, point)
	local lastPoint = LastSpawnPointByZone[zoneName]
	return not lastPoint or (point - lastPoint).Magnitude >= MIN_CONSECUTIVE_SPAWN_DISTANCE
end

local function RememberSpawnPoint(zoneName, point)
	LastSpawnPointByZone[zoneName] = point
	return point
end

local function GetZonePoint(zoneName, clearRadius)
	-- Each biome owns one explicit rectangular spawn region:
	-- Spawn=1, Desert=2, Samurai=3, Farm=4, Snow=5,
	-- Underwater=6, Volcano=7, Narmek=8.
	--.. Overlap guard: reject candidate points too close to ANY live breakable
	--.. in this zone -- closer than 3 studs, OR close enough that the new
	--.. spawn's footprint would touch theirs (clearRadius = the spawn's
	--.. half-footprint; the neighbor's radius comes from its hitbox/part size).
	--.. Horizontal (XZ) distance so tall hitboxes can't inflate the gap.
	--.. Function-scope helper on purpose -- this module is AT the 200
	--.. top-level-local limit.
	local function IsClearOfBreakables(point)
		local folder = Container and Container[zoneName]
		if not folder then return true end
		local myRadius = clearRadius or 0
		for _, b in ipairs(folder:GetChildren()) do
			local pos, otherRadius
			if b:IsA("Model") then
				local pp = b.PrimaryPart
				if pp then
					pos, otherRadius = pp.Position, math.max(pp.Size.X, pp.Size.Z) * 0.5
				else
					pos, otherRadius = b:GetPivot().Position, 0
				end
			elseif b:IsA("BasePart") then
				pos, otherRadius = b.Position, math.max(b.Size.X, b.Size.Z) * 0.5
			end
			if pos then
				local dx, dz = pos.X - point.X, pos.Z - point.Z
				local minGap = math.max(3, myRadius + otherRadius)
				if (dx * dx + dz * dz) < minGap * minGap then
					return false
				end
			end
		end
		return true
	end
	local spawnAreaFolder = workspace:FindFirstChild("SpawnArea")
	local regionName = ZONE_SPAWN_INDEX[zoneName]
	local region = spawnAreaFolder and regionName and spawnAreaFolder:FindFirstChild(regionName)
	if region and region:IsA("BasePart") then
		local halfX = math.max(0, region.Size.X * 0.5 - SPAWN_AREA_PADDING)
		local halfZ = math.max(0, region.Size.Z * 0.5 - SPAWN_AREA_PADDING)
		local point
		local tries = 0
		repeat
			tries += 1
			local localPoint = Vector3.new(
				math.random() * halfX * 2 - halfX,
				region.Size.Y * 0.5,
				math.random() * halfZ * 2 - halfZ
			)
			point = region.CFrame:PointToWorldSpace(localPoint)
			--.. region tops hover ~2 studs above the map, so snap every spawn point
			--.. down to the real ground below it -- breakables must SIT on the floor,
			--.. never float at region height. Skip other breakables and players.
			local params = RaycastParams.new()
			params.FilterType = Enum.RaycastFilterType.Exclude
			params.RespectCanCollide = true -- zone volumes/shadows/fx are CanCollide false
			local exclude = {spawnAreaFolder}
			local breakablesFolder = workspace:FindFirstChild("Breakables")
			if breakablesFolder then table.insert(exclude, breakablesFolder) end
			for _, plr in ipairs(Players:GetPlayers()) do
				if plr.Character then table.insert(exclude, plr.Character) end
			end
			params.FilterDescendantsInstances = exclude
			local hit = workspace:Raycast(point + Vector3.new(0, 4, 0), Vector3.new(0, -120, 0), params)
			if hit then
				point = Vector3.new(point.X, hit.Position.Y, point.Z)
			end
		until (IsFarEnoughFromLastSpawn(zoneName, point) and IsClearOfBreakables(point)) or tries >= 40
		return RememberSpawnPoint(zoneName, point)
	end

	-- Safe fallback for a missing/misnamed SpawnArea part.
	local Zone = ZoneGroups[zoneName]
	if not Zone then
		Zone = ZonePlus.new(workspace.Zones[zoneName])
		ZoneGroups[zoneName] = Zone
	end

	local point
	local attempts = 0
	repeat
		attempts += 1
		local randomVector, touchingParts = Zone:getRandomPoint()
		local params = RaycastParams.new()
		params.FilterDescendantsInstances = touchingParts
		params.FilterType = Enum.RaycastFilterType.Whitelist
		local result = workspace:Raycast(randomVector + Vector3.new(0, 1, 0), Vector3.new(0, -2, 0), params)
		point = result and result.Position
		if not point and attempts >= 50 then point = randomVector end
	until (point and IsFarEnoughFromLastSpawn(zoneName, point) and IsClearOfBreakables(point)) or (point and attempts >= 50)
	return RememberSpawnPoint(zoneName, point)
end

