local function AddUprightLimbsAndFace(body, def, hrpCF, dia, len)
	local limbColor = def.LimbColor or Color3.fromRGB(46, 116, 48)
	local palmColor = def.PalmColor or Color3.fromRGB(94, 172, 76)

	local bottomY = -len * 0.5
	for side = -1, 1, 2 do
		--.. arm: slants down and outward from the upper body
		local shoulder = hrpCF * CFrame.new(side * dia * 0.52, len * 0.12, 0)
		local slant = shoulder * CFrame.Angles(0, 0, math.rad(-52 * side))
		BossLimb(body, side < 0 and "LeftArm" or "RightArm",
			Vector3.new(dia * 0.85, dia * 0.16, dia * 0.16), limbColor,
			slant * CFrame.new(side * dia * 0.42, 0, 0))
		BossHandFoot(body, side < 0 and "LeftFist" or "RightFist",
			Vector3.new(dia * 0.34, dia * 0.34, dia * 0.34), palmColor,
			slant * CFrame.new(side * dia * 0.85, 0, 0))

		--.. stubby leg + foot tucked under the body
		BossLimb(body, side < 0 and "LeftLeg" or "RightLeg",
			Vector3.new(dia * 0.5, dia * 0.2, dia * 0.2), limbColor,
			hrpCF * CFrame.new(side * dia * 0.26, bottomY - dia * 0.12, 0) * CFrame.Angles(0, 0, math.rad(90)))
		BossHandFoot(body, side < 0 and "LeftFoot" or "RightFoot",
			Vector3.new(dia * 0.3, dia * 0.34, dia * 0.48), palmColor,
			hrpCF * CFrame.new(side * dia * 0.26, bottomY - dia * 0.32, -dia * 0.06))
	end

	--.. (face plate removed 2026-08-11 at user request — SetBossExpression and the
	--.. client blink find no BossFace and safely no-op, so the system stays parked)
end

local function BuildMobileBossRig(part, def, point)
	local len = part.Size.X -- body cylinder: length along X, dia across Y/Z
	local dia = part.Size.Y

	--.. the lying cucumber's stem/vine/leaf decorations end up ON TOP of the
	--.. standing boss's head, where they read as googly-eyed face blobs (user
	--.. report) — shave the head clean on every boss
	for _, c in ipairs(part:GetChildren()) do
		if c.Name == "Stem" or c.Name == "Vine" or c.Name == "Leaf" then
			c:Destroy()
		end
	end
	local legLen = dia * 0.55

	local model = Instance.new("Model")
	model.Name = part.Name

	local hrpSize = Vector3.new(dia * 0.9, len * 0.45, dia * 0.9)
	local hrpY = len * 0.5 + legLen * 0.55 --.. body bottom floats just above the feet
	local hrpCF = CFrame.new(point + Vector3.new(0, hrpY + 0.1, 0))
		* CFrame.Angles(0, math.rad(math.random(-180, 180)), 0)

	--.. pose the (still anchored) body upright at its final spot, then carry the
	--.. welded decorations with it — same manual remap the static path uses,
	--.. because WeldConstraints don't act before the assembly is in workspace
	part.CFrame = hrpCF * CFrame.Angles(0, 0, math.rad(90))
	for _, c in ipairs(part:GetChildren()) do
		if c:IsA("BasePart") then c.CFrame = part.CFrame * c.CFrame end
	end

	AddUprightLimbsAndFace(part, def, hrpCF, dia, len)

	local hrp = Instance.new("Part")
	hrp.Name = "HumanoidRootPart"
	hrp.Size = hrpSize
	hrp.Transparency = 1
	hrp.CanCollide = true -- the ONLY collider in the rig; everything visual stays CanCollide=false
	hrp.CanQuery = false
	hrp.CanTouch = false
	hrp.CFrame = hrpCF
	hrp.Parent = model

	--.. C0 stays identity so BodyJoint.Transform works in plain HRP space
	--.. (Y = up, -Z = forward); C1 supplies the upright body rotation instead.
	local joint = Instance.new("Motor6D")
	joint.Name = "BodyJoint"
	joint.Part0 = hrp
	joint.Part1 = part
	joint.C1 = CFrame.Angles(0, 0, math.rad(-90))
	joint.Parent = hrp

	local humanoid = Instance.new("Humanoid")
	humanoid.DisplayDistanceType = Enum.HumanoidDisplayDistanceType.None
	humanoid.HealthDisplayType = Enum.HumanoidHealthDisplayType.AlwaysOff
	humanoid.MaxHealth = math.huge
	humanoid.Health = math.huge -- cosmetic only: boss HP lives in Breakables[part].HP
	humanoid.WalkSpeed = def.WalkSpeed or 11
	humanoid.HipHeight = hrpY - hrpSize.Y * 0.5
	humanoid.AutoRotate = true
	humanoid.BreakJointsOnDeath = false
	humanoid.MaxSlopeAngle = 80
	humanoid:SetStateEnabled(Enum.HumanoidStateType.Climbing, false)
	humanoid:SetStateEnabled(Enum.HumanoidStateType.Swimming, false)
	humanoid:SetStateEnabled(Enum.HumanoidStateType.Seated, false)
	humanoid.Parent = model

	part.Anchored = false
	part.Parent = model
	model.PrimaryPart = part -- BreakablesClient resolves Model clicks to PrimaryPart
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") and d ~= hrp then
			d.Massless = true
			d.CanCollide = false
		end
	end
	--.. a walking boss must never stream out mid-fight (see the far-egg lesson)
	--.. 3D voice: clients trigger these locally (roar on entrance, boom on slam
	--.. impact, whoosh on the charge dash) — see BossMotionClient
	local function bossSound(name, id, volume, rollOff)
		local sound = Instance.new("Sound")
		sound.Name = name
		sound.SoundId = id
		sound.Volume = volume
		sound.RollOffMaxDistance = rollOff
		sound.RollOffMinDistance = 14
		sound.Parent = hrp
	end
	bossSound("RoarSound", "rbxassetid://140520408524334", 0.9, 240)
	bossSound("SlamBoomSound", "rbxassetid://9113217346", 0.85, 220)
	bossSound("ChargeWhooshSound", "rbxassetid://90661028523798", 0.75, 160)

	pcall(function()
		-- Bosses remain authoritative on the server but may stream out for players in
		-- distant biomes. Atomic keeps the rig complete whenever it streams back in.
		model.ModelStreamingMode = Enum.ModelStreamingMode.Atomic
	end)
	model:SetAttribute("MobileBoss", true)

	return model
end

