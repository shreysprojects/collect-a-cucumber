local function ApplySuperStrengthToPlayer(Player, enabled)
	if not Player or Player.Parent ~= Players then return end
	local alreadyEnabled = Player:GetAttribute("SuperStrengthActive") == true
	local character = Player.Character
	local existingBaseScale = character and tonumber(character:GetAttribute("SuperStrengthBaseScale"))
	if alreadyEnabled == enabled and ((enabled and existingBaseScale) or (not enabled and not existingBaseScale)) then return end
	Player:SetAttribute("SuperStrengthActive", enabled or nil)
	if character then
		local baseScale = existingBaseScale
		if enabled and not baseScale then
			baseScale = character:GetScale()
			character:SetAttribute("SuperStrengthBaseScale", baseScale)
			pcall(function() character:ScaleTo(baseScale * 2) end)
		elseif not enabled and baseScale then
			pcall(function() character:ScaleTo(baseScale) end)
			character:SetAttribute("SuperStrengthBaseScale", nil)
		end
	end
	RefreshEventWalkSpeed(Player)
end

local function FindPlayerBiome(Player)
	local character = Player and Player.Character
	local root = character and character:FindFirstChild("HumanoidRootPart")
	local zones = workspace:FindFirstChild("Zones")
	if not root or not zones then return nil end
	local position = root.Position
	for _, zoneName in ipairs(ZONES) do
		local folder = zones:FindFirstChild(zoneName)
		if folder then
			for _, part in ipairs(folder:GetChildren()) do
				if part:IsA("BasePart") then
					local offset = part.CFrame:PointToObjectSpace(position)
					if math.abs(offset.X) <= part.Size.X * 0.5
						and math.abs(offset.Z) <= part.Size.Z * 0.5
						and math.abs(offset.Y) <= 60 then
						return zoneName
					end
				end
			end
		end
	end
	return nil
end

local function RefreshPlayerEventBiome(Player)
	if not Player or Player.Parent ~= Players then return end
	local zoneName = FindPlayerBiome(Player)
	if zoneName then
		PlayerEventZone[Player] = zoneName
		Player:SetAttribute("CurrentBiome", zoneName)
	else
		--.. the LOBBY (and the bank courtyard/deck behind it) is a definitive
		--.. "no biome" area: drop the sticky zone there so SUPER STRENGTH
		--.. reverts the player to their pre-event size the moment they come
		--.. home (user report 2026-08-26: the sticky fallback kept players
		--.. giant in the lobby until the event expired). The stickiness stays
		--.. for the gaps BETWEEN biome volumes, where it prevents flicker.
		local character = Player.Character
		local root = character and character:FindFirstChild("HumanoidRootPart")
		if root then
			local p = root.Position
			local inHome = false
			local lobbyArea = workspace:FindFirstChild("Game")
			lobbyArea = lobbyArea and lobbyArea:FindFirstChild("Area 1")
			lobbyArea = lobbyArea and lobbyArea:FindFirstChild("Assets")
			lobbyArea = lobbyArea and lobbyArea:FindFirstChild("LobbyArea")
			if lobbyArea then
				local o = lobbyArea.CFrame:PointToObjectSpace(p)
				inHome = math.abs(o.X) <= lobbyArea.Size.X * 0.5 + 4
					and math.abs(o.Z) <= lobbyArea.Size.Z * 0.5 + 4
					and math.abs(o.Y) <= lobbyArea.Size.Y * 0.5 + 30
			end
			if not inHome and p.X >= 30 and p.X <= 100 and p.Z >= -55 and p.Z <= 50 and p.Y >= -4 and p.Y <= 44 then
				inHome = true -- bank courtyard/apron box (mirrors BossBarClient.inBank)
			end
			if not inHome then
				--.. live bank deck footprint: the deck regenerates on vault
				--.. upgrades, so it must be looked up per call
				local bank = workspace:FindFirstChild("CucumberBank")
				local slab = bank and bank:FindFirstChild("DeckSlab", true)
				if slab then
					local o = slab.CFrame:PointToObjectSpace(p)
					inHome = math.abs(o.X) <= slab.Size.X * 0.5 + 4
						and math.abs(o.Z) <= slab.Size.Z * 0.5 + 4
						and math.abs(o.Y) <= 40
				end
			end
			if inHome then
				PlayerEventZone[Player] = nil
			end
		end
		zoneName = PlayerEventZone[Player] -- sticky between biome volumes, like the HUD
	end
	ApplySuperStrengthToPlayer(Player, zoneName ~= nil and IsEventActive(zoneName, "SuperStrength"))
end

