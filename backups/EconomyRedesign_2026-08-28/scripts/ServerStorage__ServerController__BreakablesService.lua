local function PetsInRange(Player, part)
	--.. Pet damage represents the equipped swarm as one combined strike, so every
	--.. readable pet must physically arrive before that combined strike may land.
	--.. Missing/mid-replication models fail closed; otherwise the first target after
	--.. spawn/equip can receive one full pet hit from across the biome.
	local char = Player.Character
	local folder = char and char:FindFirstChild("Pets")
	if not folder then return false end

	--.. Measured horizontally because pets use ground-relative vertical placement.
	local reach = math.max(part.Size.X, part.Size.Z) * 0.5 + PET_ATTACK_RANGE
	local flat = Vector2.new(part.Position.X, part.Position.Z)
	local sawPet = false
	for _, pet in ipairs(folder:GetChildren()) do
		local root = pet:IsA("Model") and pet.PrimaryPart
		if root then
			sawPet = true
			if (Vector2.new(root.Position.X, root.Position.Z) - flat).Magnitude > reach then
				return false
			end
		end
	end
	return sawPet
end
