local PET_SWITCH_HITS = 3 -- pickaxe hits on a NEW cucumber before pets abandon their current one
local PendingSwitch = {} -- [player] = {Part, Hits}; counts strikes toward a pet retarget

local function Commit(Player, part, countedHit)
	if Targets[Player] == part then
		PendingSwitch[Player] = nil
		return
	end

	--.. pets already working a live cucumber: don't yank the swarm on a stray
	--.. click — the player has to land PET_SWITCH_HITS real hits on the new
	--.. target first (their own pickaxe damage still applies from hit one).
	--.. With no live target the switch stays instant, exactly as before.
	local current = Targets[Player]
	if current and Breakables[current] then
		local pending = PendingSwitch[Player]
		if not pending or pending.Part ~= part then
			pending = {Part = part; Hits = 0}
			PendingSwitch[Player] = pending
		end
		if countedHit then
			pending.Hits += 1
		end
		if pending.Hits < PET_SWITCH_HITS then
			return
		end
	end
	PendingSwitch[Player] = nil

	Targets[Player] = part
	NextAuto[Player] = 0 -- pets start immediately (next loop pass, <=0.25s)
	local pd = Player:FindFirstChild("PlayerData")
	local ov = pd and pd:FindFirstChild("AutoTarget")
	if ov then ov.Value = part end -- pets fly out the moment the target commits
	Network:FireClient(Player, "BreakableTargeted", {
		Part = part;
		Golden = Breakables[part].Type.Golden == true;
	})
end

