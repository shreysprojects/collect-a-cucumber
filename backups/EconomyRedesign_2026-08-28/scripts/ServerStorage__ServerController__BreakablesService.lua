--.. Temporary ragdoll for boss knockbacks: swap every limb Motor6D for a limited
--.. BallSocket, let the fling physics tumble the body, then put it all back.
--.. The root motor (HRP->torso) stays ENABLED so the camera/root follows the body.
--.. Constraints replicate, the owning client simulates — no custom client code.
local BOSS_RAGDOLL_TIME = 1.4

RagdollCharacter = function(char, duration)
	local humanoid = char and char:FindFirstChildOfClass("Humanoid")
	if not humanoid or humanoid.Health <= 0 then return end
	if char:GetAttribute("BossRagdoll") then return end
	char:SetAttribute("BossRagdoll", true)

	humanoid.PlatformStand = true

	--.. this game's avatars are PHYSICS RIGS: BallSocketConstraints carry the body
	--.. and AnimationConstraints drive the pose on top (see cucumber avatar rig
	--.. notes). Cutting the pose drivers over the existing sockets IS the ragdoll.
	--.. The Motor6D socket-swap below is only the fallback for standard rigs.
	local constraints = {}
	for _, d in ipairs(char:GetDescendants()) do
		if d:IsA("AnimationConstraint") and d.Enabled then
			--.. NEVER cut the Root joint (HumanoidRootPart->LowerTorso): it is the ONE
			--.. AnimationConstraint with no BallSocket underneath, so disabling it
			--.. detaches the whole body from the root — that was the "broken ragdoll".
			--.. With Root kept + PlatformStand, the assembly tumbles as one while every
			--.. socket-backed joint goes limp.
			local a0p = d.Attachment0 and d.Attachment0.Parent
			local a1p = d.Attachment1 and d.Attachment1.Parent
			local touchesRoot = (a0p and a0p.Name == "HumanoidRootPart") or (a1p and a1p.Name == "HumanoidRootPart")
			if not touchesRoot then
				constraints[#constraints + 1] = d
			end
		end
	end

	local motorUndo = {}
	if #constraints > 0 then
		for _, c in ipairs(constraints) do
			c.Enabled = false
		end
	else
		for _, motor in ipairs(char:GetDescendants()) do
			if motor:IsA("Motor6D") and motor.Enabled
				and motor.Name ~= "RootJoint" and motor.Name ~= "Root"
				and motor.Part0 and motor.Part0.Parent == char
				and motor.Part1 and motor.Part1.Parent == char then
				local a0 = Instance.new("Attachment")
				a0.CFrame = motor.C0
				a0.Parent = motor.Part0
				local a1 = Instance.new("Attachment")
				a1.CFrame = motor.C1
				a1.Parent = motor.Part1
				local socket = Instance.new("BallSocketConstraint")
				socket.Attachment0 = a0
				socket.Attachment1 = a1
				socket.LimitsEnabled = true
				socket.UpperAngle = 45
				socket.TwistLimitsEnabled = true
				socket.Parent = motor.Part0
				motor.Enabled = false
				motorUndo[#motorUndo + 1] = {motor, a0, a1, socket}
			end
		end
	end

	task.delay(duration or BOSS_RAGDOLL_TIME, function()
		for _, c in ipairs(constraints) do
			if c.Parent then c.Enabled = true end
		end
		for _, entry in ipairs(motorUndo) do
			local motor, a0, a1, socket = entry[1], entry[2], entry[3], entry[4]
			if motor.Parent then motor.Enabled = true end
			socket:Destroy()
			a0:Destroy()
			a1:Destroy()
		end
		if char.Parent then
			char:SetAttribute("BossRagdoll", nil)
			if humanoid.Parent then
				humanoid.PlatformStand = false
				humanoid:ChangeState(Enum.HumanoidStateType.GettingUp)
			end
		end
	end)
end

--.. fling one character away from a point — the same feel as BossKnockback's
--.. on-strike retaliation, reused by the slam AOE and the charge trample
local function FlingPlayer(hrp, center, force, up)
	local offset = (hrp.Position - center) * Vector3.new(1, 0, 1)
	local direction = offset.Magnitude > 0.1 and offset.Unit or Vector3.new(0, 0, 1)
	local velocity = direction * force + Vector3.new(0, up, 0)
	hrp.AssemblyLinearVelocity = velocity

	local shove = Instance.new("BodyVelocity")
	shove.Name = "BossAttackShove"
	shove.MaxForce = Vector3.new(90000, 90000, 90000)
	shove.P = 2500
	shove.Velocity = velocity
	shove.Parent = hrp
	game:GetService("Debris"):AddItem(shove, 0.24)

	if hrp.Parent then RagdollCharacter(hrp.Parent) end
end

local function FlingPlayersFrom(center, radius, force, up)
	for _, plr in ipairs(Players:GetPlayers()) do
		local char = plr.Character
		local hrp = char and char:FindFirstChild("HumanoidRootPart")
		if hrp and (hrp.Position - center).Magnitude <= radius then
			FlingPlayer(hrp, center, force, up)
		end
	end
end

local function StartBossBrain(part, model, point)
	task.spawn(function()
		local hrp = model:FindFirstChild("HumanoidRootPart")
		local humanoid = model:FindFirstChildOfClass("Humanoid")
		if not hrp or not humanoid then return end
		pcall(function() hrp:SetNetworkOwner(nil) end) -- server-authoritative movement

		local baseWalk = humanoid.WalkSpeed
		local enraged = false
		local nextWander = 0
		local nextAttack = os.clock() + 3.5 -- short grace after the spawn announcement
		model:SetAttribute("BossState", "Spawning") -- clients play the rise + roar
		model:SetAttribute("SlamCount", 0)

		local function alive()
			return Breakables[part] ~= nil and model.Parent ~= nil
		end

		local function hpFraction()
			local data = Breakables[part]
			if not data then return 0 end
			return math.clamp(data.HP / data.MaxHP, 0, 1)
		end

		--.. sleep in small steps so a mid-windup kill ends the sequence promptly
		local function waitAlive(duration)
			local deadline = os.clock() + duration
			while alive() and os.clock() < deadline do
				task.wait(0.1)
			end
			return alive()
		end

		local function nearestTarget()
			local here = hrp.Position
			local best, bestDist
			for _, plr in ipairs(Players:GetPlayers()) do
				local char = plr.Character
				local phrp = char and char:FindFirstChild("HumanoidRootPart")
				if phrp then
					local d = (phrp.Position - here).Magnitude
					local fromPad = ((phrp.Position - point) * Vector3.new(1, 0, 1)).Magnitude
					--.. only react to players who are actually AT the fight; a player
					--.. running for the hills should not steer the boss off its pad
					if d <= BOSS_AGGRO_RANGE and fromPad <= BOSS_LEASH_RADIUS + 26 and (not bestDist or d < bestDist) then
						best, bestDist = phrp, d
					end
				end
			end
			return best, bestDist
		end

		local function groundUnderBoss()
			return Vector3.new(hrp.Position.X, point.Y, hrp.Position.Z)
		end

		local function doSlam()
			humanoid:MoveTo(hrp.Position) -- plant feet
			model:SetAttribute("SlamPos", groundUnderBoss())
			model:SetAttribute("BossState", "SlamWindup")
			SetBossExpression(part, "Windup")
			if not waitAlive(BOSS_SLAM_WINDUP) then return end

			local center = groundUnderBoss()
			model:SetAttribute("SlamPos", center)
			--.. the count bump is the replicated "impact happened" signal for clients
			model:SetAttribute("SlamCount", (model:GetAttribute("SlamCount") or 0) + 1)
			FlingPlayersFrom(center, BOSS_SLAM_RADIUS, BOSS_SLAM_FORCE, BOSS_SLAM_UP)
			model:SetAttribute("BossState", "SlamRecover")
			RefreshBossExpression(part, Breakables[part])
			waitAlive(0.8)
		end

		--.. escape dash destination: bolt for the leash edge on the far side of the
		--.. pad from the victim, so a cornered boss breaks away with one long dash
		local function chargeDest(victim)
			local fromPoint = (victim.Position - point) * Vector3.new(1, 0, 1)
			if fromPoint.Magnitude > 2 then
				return point - fromPoint.Unit * BOSS_LEASH_RADIUS
			end
			--.. victim is standing on the pad centre: head directly away from them
			local away = (hrp.Position - victim.Position) * Vector3.new(1, 0, 1)
			local dir = away.Magnitude > 0.5 and away.Unit or Vector3.new(0, 0, 1)
			return point + dir * BOSS_LEASH_RADIUS
		end

		local function doCharge(victim)
			--.. if the run-up would be trivial anyway, a slam reads far better
			if ((chargeDest(victim) - hrp.Position) * Vector3.new(1, 0, 1)).Magnitude < 10 then
				doSlam()
				return
			end

			humanoid:MoveTo(hrp.Position)
			--.. square up on the escape route so the windup reads as "it's about to bolt"
			pcall(function()
				local face = chargeDest(victim)
				hrp.CFrame = CFrame.lookAt(hrp.Position, Vector3.new(face.X, hrp.Position.Y, face.Z))
			end)
			model:SetAttribute("BossState", "ChargeWindup")
			SetBossExpression(part, "Windup")
			if not waitAlive(BOSS_CHARGE_WINDUP) then return end

			--.. flee from where they ARE when the windup ends; anyone standing on
			--.. the escape route still gets trampled
			local dest = chargeDest(victim)

			model:SetAttribute("BossState", "Charging")
			SetBossExpression(part, "Charge")
			humanoid.WalkSpeed = BOSS_CHARGE_SPEED
			humanoid:MoveTo(dest)

			local hitRadius = math.max(part.Size.Y, part.Size.Z) * 0.5 + BOSS_CHARGE_HIT_PAD
			local struck = {}
			local deadline = os.clock() + 2.4
			while alive() and os.clock() < deadline do
				local herePos = hrp.Position
				for _, plr in ipairs(Players:GetPlayers()) do
					local char = plr.Character
					local phrp = char and char:FindFirstChild("HumanoidRootPart")
					if phrp and not struck[plr] and (phrp.Position - herePos).Magnitude <= hitRadius then
						struck[plr] = true
						FlingPlayer(phrp, herePos, BOSS_SLAM_FORCE, BOSS_SLAM_UP)
					end
				end
				if ((herePos - dest) * Vector3.new(1, 0, 1)).Magnitude < 4 then break end
				task.wait(0.08)
			end

			humanoid.WalkSpeed = baseWalk
			model:SetAttribute("BossState", "SlamRecover")
			RefreshBossExpression(part, Breakables[part])
			waitAlive(0.6)
		end

		local function maybeEnrage()
			if enraged or hpFraction() > BOSS_ENRAGE_HP then return end
			enraged = true
			model:SetAttribute("Enraged", true)
			baseWalk = baseWalk * BOSS_ENRAGE_WALK_MULT
			humanoid.WalkSpeed = baseWalk
			pcall(function()
				local glow = part:FindFirstChildOfClass("PointLight")
				if glow then
					glow.Color = Color3.fromRGB(255, 70, 40)
					glow.Brightness = 2.4
					glow.Range = 32
				end
				part.Color = part.Color:Lerp(Color3.fromRGB(190, 60, 40), 0.35)
			end)
		end

		--.. entrance beat: hold still while every client plays the rise + roar
		if waitAlive(1.3) then
			model:SetAttribute("BossState", "Chase")
		end

		while alive() do
			maybeEnrage()
			local target, dist = nearestTarget()
			if target then
				--.. run AWAY from the nearest player, kept inside the leash circle.
				--.. When backed against the leash edge, slide along it whichever way
				--.. gains distance, so the boss circles the pad instead of standing
				--.. pinned against the invisible wall.
				local herePos = hrp.Position
				local away = (herePos - target.Position) * Vector3.new(1, 0, 1)
				away = away.Magnitude > 0.5 and away.Unit or Vector3.new(1, 0, 0)
				local offset = ((herePos + away * BOSS_FLEE_STEP) - point) * Vector3.new(1, 0, 1)
				if offset.Magnitude > BOSS_LEASH_RADIUS then
					local radial = (herePos - point) * Vector3.new(1, 0, 1)
					radial = radial.Magnitude > 0.5 and radial.Unit or away
					local tangent = Vector3.new(-radial.Z, 0, radial.X)
					if ((herePos + tangent * BOSS_FLEE_STEP) - target.Position).Magnitude < ((herePos - tangent * BOSS_FLEE_STEP) - target.Position).Magnitude then
						tangent = -tangent
					end
					offset = ((herePos + tangent * BOSS_FLEE_STEP) - point) * Vector3.new(1, 0, 1)
					if offset.Magnitude > BOSS_LEASH_RADIUS then
						offset = offset.Unit * BOSS_LEASH_RADIUS
					end
				end
				humanoid:MoveTo(point + offset)

				--.. a player who runs the boss down still eats a defensive attack:
				--.. the slam shoves the pursuer off, the charge is an escape dash
				if os.clock() >= nextAttack and dist <= BOSS_SLAM_RADIUS + 4 then
					if hpFraction() <= BOSS_CHARGE_HP and math.random() < BOSS_CHARGE_CHANCE then
						doCharge(target)
					else
						doSlam()
					end
					if not alive() then break end
					humanoid.WalkSpeed = baseWalk
					model:SetAttribute("BossState", "Chase")
					nextAttack = os.clock() + (enraged and BOSS_ATTACK_INTERVAL_ENRAGED or BOSS_ATTACK_INTERVAL)
				end
			elseif os.clock() >= nextWander then
				--.. nobody around: amble near the pad
				nextWander = os.clock() + 3.5
				local angle = math.random() * math.pi * 2
				local r = 4 + math.random() * (BOSS_WANDER_RADIUS - 4)
				humanoid:MoveTo(point + Vector3.new(math.cos(angle) * r, 0, math.sin(angle) * r))
			end

			task.wait(BOSS_REPATH)
		end
	end)
end

